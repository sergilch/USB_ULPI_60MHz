#!/usr/bin/env python3
"""gen_xdc.py - writes constraints/aio_zedboard.xdc for aio_fpga_top on a
Digilent ZedBoard Rev D.2 (XC7Z020CLG484-2).

The FMC pins come from ../easyeda/fmc_pinmap.csv (written by the schematic
generator, the single source of the pin map); the port of a net is its name in
lower case without the "_F" suffix.  The script checks that every FMC port of
rtl/aio_fpga_top.v has exactly one pin and every mapped net has a port, so a
change of the board pin map or of the top level that does not match fails here.

    python3 gen_xdc.py
"""
import csv
import os
import re
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
CSV = os.path.join(HERE, "..", "easyeda", "fmc_pinmap.csv")
TOP = os.path.join(HERE, "rtl", "aio_fpga_top.v")
OUT = os.path.join(HERE, "constraints", "aio_zedboard.xdc")

# ZedBoard Rev D.2 carrier pins (zedboard_sch.pdf sheet 9).  Banks 34 / 35 are at
# VADJ = 2.5 V (J18), banks 13 / 33 at 3.3 V.
CARRIER = [
    # port         pin     iostandard  note
    ("gclk",       "Y9",   "LVCMOS33", "GCLK 100 MHz oscillator, bank 13"),
    ("btn_rst",    "P16",  "LVCMOS25", "BTNC, bank 34"),
    ("sw[0]",      "F22",  "LVCMOS25", "SW0, bank 35: UART block select"),
    ("sw[1]",      "G22",  "LVCMOS25", "SW1, bank 35: UART block select"),
    ("led[0]",     "T22",  "LVCMOS33", "LD0 MMCM locked"),
    ("led[1]",     "T21",  "LVCMOS33", "LD1 TX active"),
    ("led[2]",     "U22",  "LVCMOS33", "LD2 RX squelch / armed"),
    ("led[3]",     "U21",  "LVCMOS33", "LD3 PLL lock"),
    ("led[4]",     "V22",  "LVCMOS33", "LD4 CDR CLK_RX alive"),
    ("led[5]",     "W22",  "LVCMOS33", "LD5 CDR packets OK"),
    ("led[6]",     "U19",  "LVCMOS33", "LD6 UART select [0]"),
    ("led[7]",     "U14",  "LVCMOS33", "LD7 UART select [1]"),
    # PmodUSBUART on JA, upper row (pin 1 RTS, 2 TXD from the FPGA, 3 RXD into
    # the FPGA, 4 CTS; Digilent Pmod type 4 names the signals from the host).
    # If the link stays silent, swap these two pins.
    ("uart_txd",   "AA11", "LVCMOS33", "JA2 -> PmodUSBUART RXD"),
    ("uart_rxd",   "Y10",  "LVCMOS33", "JA3 <- PmodUSBUART TXD"),
]

DIFF_TERM_IN = {"clk_rx", "hs_rxd", "clk_bit_a", "clk60_a"}   # rx_out: DIFF_TERM in RTL (IBUFDS_DIFF_OUT)
FAST_OUT = ["tx_en", "fs_oe", "fs_dat", "fs_se0", "fs_ls"]    # 480 Mbit/s and FS/LS edges


def port_of(net):
    p = net.lower()
    return p[:-2] if p.endswith("_f") else p


def top_ports():
    src = open(TOP).read()
    i = src.index("module aio_fpga_top")
    hdr = src[i:src.index(");", i)]
    ports = {}
    for m in re.finditer(r"\b(input|output)\s+wire\s*(\[[^\]]*\])?\s*([^;\n]*)", hdr):
        for name in re.findall(r"\b([a-z_][a-z0-9_]*)\b", m.group(3).split("//")[0]):
            ports[name] = (m.group(1), m.group(2))
    return ports


def main():
    ports = top_ports()
    rows, seen = [], {}
    for r in csv.DictReader(open(CSV)):
        if not r["zedboard_pin"] or r["net"] in ("(free)", "-"):
            continue
        if r["fmc_pin"] in seen:                       # shared nets are listed once per block
            continue
        seen[r["fmc_pin"]] = r
        rows.append(r)
    errs = []
    fmc_ports = set()
    for r in rows:
        p = port_of(r["net"])
        fmc_ports.add(p)
        if p not in ports:
            errs.append("net %s (FMC %s): no port %s in aio_fpga_top" % (r["net"], r["fmc_pin"], p))
    carrier = {c[0].split("[")[0] for c in CARRIER}
    for p in ports:
        if p not in fmc_ports and p not in carrier:
            errs.append("port %s has no pin" % p)
    if len(fmc_ports) != len(rows):
        errs.append("two FMC pins map to one port")
    for e in errs:
        print("ERROR:", e)
    if errs:
        sys.exit(1)

    L = []
    w = L.append
    w("## aio_zedboard.xdc - aio_fpga_top on a Digilent ZedBoard Rev D.2 (XC7Z020CLG484-2)")
    w("## GENERATED by gen_xdc.py from ../easyeda/fmc_pinmap.csv - do not edit the pin section by hand.")
    w("## VADJ (J18) must be 2.5 V: LVDS_25 outputs and DIFF_TERM need VCCO = 2.5 V in banks 34 / 35.")
    w("")
    w("# ---- ZedBoard ----")
    for port, pin, std, note in CARRIER:
        w("set_property -dict {PACKAGE_PIN %-5s IOSTANDARD %s} [get_ports {%s}]%s;# %s"
          % (pin, std, port, " " * max(1, 14 - len(port)), note))
    w("")
    w("# ---- FMC LPC (VITA 57.1) ----")
    w("#   port            ZedBoard  FMC   LA signal      board net            block")
    for r in rows:
        p = port_of(r["net"])
        w("set_property PACKAGE_PIN %-5s [get_ports %-16s] ;# %-4s %-13s %-20s %s%s"
          % (r["zedboard_pin"], p, r["fmc_pin"], r["la_signal"], r["net"], r["block"],
             "  " + r["zedboard_clock_capable"] if r["zedboard_clock_capable"] else ""))
    diff = sorted({port_of(r["net"]) for r in rows if r["iostandard"] == "LVDS_25"})
    se = sorted({port_of(r["net"]) for r in rows if r["iostandard"] == "LVCMOS25"})
    w("")
    w("set_property IOSTANDARD LVDS_25  [get_ports {%s}]" % " ".join(diff))
    term = [p for p in diff if re.sub(r"_[pn]$", "", p) in DIFF_TERM_IN]
    w("set_property DIFF_TERM  TRUE     [get_ports {%s}]" % " ".join(term))
    w("set_property IOSTANDARD LVCMOS25 [get_ports {%s}]" % " ".join(se))
    w("set_property SLEW FAST [get_ports {%s}]" % " ".join(FAST_OUT))
    w("set_property DRIVE 8   [get_ports {%s}]" % " ".join(FAST_OUT))
    w(TIMING)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(L) + "\n")
    print("%s: %d FMC pins (%d LVDS_25 ports, %d LVCMOS25), %d carrier pins"
          % (os.path.relpath(OUT, HERE), len(rows), len(diff), len(se), len(CARRIER)))


TIMING = r"""
# ---- clocks ----
create_clock -period 10.000 -name gclk      [get_ports gclk]          ;# 100 MHz; MMCM outputs derived
create_clock -period  2.083 -name clk_rx    [get_ports clk_rx_p]      ;# CDR recovered clock, 480 MHz
create_clock -period  2.083 -name clk_bit_a [get_ports clk_bit_a_p]   ;# PLL board, 480 MHz
create_clock -period 16.667 -name clk60_a   [get_ports clk60_a_p]     ;# PLL board /8
create_clock -period 41.667 -name ref_dig   [get_ports ref_dig]       ;# 24 MHz (19.2 / 26 also fit)
# usb_clk_gen's clk60 (BUFG) is a generated clock of CLK_BIT_A (/8)
create_generated_clock -name clk60_gen -source [get_ports clk_bit_a_p] -divide_by 8 \
    [get_pins -hierarchical -filter {NAME =~ *u_pll/u_cg*clk60_reg/Q}]

# The MMCM must share the clock region of bank 34 (its 480 MHz output drives
# the RX sampler's BUFIO / BUFR).  Vivado places it there by itself; to pin it:
# set_property LOC MMCME2_ADV_X1Y0 [get_cells u_mmcm/mmcm_adv_inst]   ;# check the region in the device view

# ---- clock domain crossings ----
# PLL block: the 60 <-> 480 boundary of usb_clk_gen transfers on ld (E4), as in
# constraints/usb_phy.sdc of the PHY (multicycle 4 / 3).
set_multicycle_path -setup 4 -from [get_clocks clk60_gen] -to [get_clocks clk_bit_a]
set_multicycle_path -hold  3 -from [get_clocks clk60_gen] -to [get_clocks clk_bit_a]
set_multicycle_path -setup 4 -from [get_clocks clk_bit_a] -to [get_clocks clk60_gen] -end
set_multicycle_path -hold  3 -from [get_clocks clk_bit_a] -to [get_clocks clk60_gen] -end
# Everything else between the groups goes through 2-FF synchronisers, toggle
# handshakes, Gray-coded counters or the RX capture BRAM (read after `done`).
#   sys:  MMCM 240 / 200 / 60 MHz (TX OSERDESE2 CLK / CLKDIV are synchronous)
#   rx:   MMCM 480 MHz (BUFIO) and BUFR /4 of the RX sampler
set_clock_groups -asynchronous \
    -group [get_clocks -of_objects [get_pins {u_mmcm/CLKOUT1 u_mmcm/CLKOUT2 u_mmcm/CLKOUT3}]] \
    -group [get_clocks -of_objects [get_pins {u_mmcm/CLKOUT0 u_bufr_rx/O}]] \
    -group [get_clocks -include_generated_clocks clk_rx] \
    -group [get_clocks -include_generated_clocks clk_bit_a] \
    -group [get_clocks clk60_a] \
    -group [get_clocks ref_dig]
# PLL: CLK60_A as data into the clk_bit sampler (phase check), asynchronous by design.
set_false_path -to [get_pins -hierarchical -filter {NAME =~ *u_pll/u_meas*bs_reg[0]/D}]

# ---- I/O ----
# CDR: HS_RXD is launched by the board on the CLK_RX rising edge (EP29 tpd
# 0.42 ns + NB6L14 output skew); the capture is tuned with IDLY (eye scan), so
# the input delay is a sanity bound, not a sign-off.
# Window 0.25 .. 0.65 ns = EP29 tpd 0.42 ns typ +- 0.15 ns, NB6L14 Q1/Q2 skew
# <= 20 ps, matched traces (cdr_board.md); the 0.2 .. 0.9 ns guess left no
# tap meeting both checks.  The BUFIO clock reaches the ISERDESE2 ~2.8 ns after
# the pin, the data at IDELAY tap 0 ~1.45 ns: tap 0 fails hold by ~1.3 ns,
# tap 22 failed setup by 0.35 ns (old window).  Vivado times the IDELAY at
# IDELAY_VALUE = IDLY0 = 19 (reset value of IDLY); the eye scan trims it.
set_input_delay -clock clk_rx -max 0.65 [get_ports {hs_rxd_p}]
set_input_delay -clock clk_rx -min 0.25 [get_ports {hs_rxd_p}]
# RX_OUT, SQUELCH_A, DISC_A are oversampled by ISERDESE2s; the OSERDESE2
# outputs (TX_IN, TX_EN, FS_*, DPAT) have a fixed CLK-to-OQ; the rest is static,
# slow (SPI, ADF4002 bus) or asynchronous.
set_false_path -from [get_ports {rx_out_p rx_out_n squelch_a disc_a vbus_det rxrcv rxdp rxdm \
    muxout pll_adc_sdo cdr_adc_sdo uart_rxd btn_rst sw[*]}]
set_false_path -to [get_ports {dp_pullup_en hs_term_en pd_en0 pd_en1 fs_suspnd rx_en \
    tx_dac_cs_n rx_dac_cs_n pll_dac_cs_n pll_adc_cs_n cdr_dac_cs_n cdr_adc_cs_n spi_sck spi_sdi \
    adf_* pll_vco_off lf_dis ol_en cdcm_off refsrc* oe24 oe19 \
    cdr_en cdr_set dsel* cdr_vco_off csw_* uart_txd led[*]}]
"""

if __name__ == "__main__":
    main()
