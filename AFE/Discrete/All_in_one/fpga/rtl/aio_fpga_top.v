//-----------------------------------------------------------------------------
// aio_fpga_top.v - FPGA design for the all-in-one discrete USB 2.0 AFE board
//                  (TX + RX + PLL + CDR, AFE/Discrete/All_in_one) on a
//                  Digilent ZedBoard Rev D.2 (XC7Z020CLG484-2), FMC LPC
//
// The four block designs of the single boards, unchanged in function and
// register map, side by side (aio_tx_blk / aio_rx_blk / aio_pll_blk /
// aio_cdr_blk; each a copy of its board's *_fpga_top without the clocking):
//
//   block  ID   board FPGA design                 host script
//   TX     'T'  Transmitter/fpga  tx_fpga_top     (none; UART protocol W / R)
//   RX     'R'  Receiver/fpga     rx_fpga_top     Receiver/host/rx_host.py
//   PLL    'P'  PLL/fpga          pll_fpga_top    PLL/host/pll_host.py
//   CDR    'C'  CDR/fpga          cdr_fpga_top    CDR/host/cdr_host.py
//
// Pins: FMC map of ../easyeda/fmc_pinmap.csv (constraints/aio_zedboard.xdc,
// generated by gen_xdc.py).  The port name is the board net in lower case
// without the "_F" suffix (SPI_SCK_F -> spi_sck, ADF_CE -> adf_ce).
//
// Carrier I/O (ZedBoard):
//   gclk      Y9, 100 MHz oscillator (bank 13)
//   btn_rst   BTNC: MMCM reset, all blocks reset (active high)
//   sw[1:0]   SW1:SW0 select the block on the UART: 00 TX, 01 RX, 10 PLL, 11 CDR
//   uart_*    PmodUSBUART on JA (bank 13, 3.3 V): the ZedBoard's own USB-UART
//             is wired to the PS (MIO48 / 49), not to the PL.  All four blocks
//             run at BAUD (921600; the TX board's default was 115200).
//   led[7:0]  LD0 MMCM locked, LD1 TX active, LD2 RX squelch / armed,
//             LD3 PLL lock (usb_pll_lock_det), LD4 CDR CLK_RX alive,
//             LD5 CDR packets OK, LD7:LD6 UART block selected
//
// Clocking (DS187 -2 limits: BUFIO 680 MHz, BUFR 375 MHz, BUFG 628 MHz):
//   gclk -> IBUF -> BUFG -> MMCME2_BASE, VCO 1200 MHz:
//     CLKOUT0 480 MHz -> BUFIO clk480 + BUFR /4 clkdiv (120 MHz): RX sampler.
//                        The MMCM must be in the clock region of bank 34
//                        (RX_OUT / SQUELCH_A / DISC_A); Vivado places it there
//                        because of the BUFIO / BUFR it drives.
//     CLKOUT1 240 MHz -> BUFG clk240: TX OSERDESE2 CLK, CDR DPAT OSERDESE2 CLK
//     CLKOUT2 200 MHz -> BUFG clk200: one IDELAYCTRL (RX + CDR IDELAYE2, bank 34)
//     CLKOUT3  60 MHz -> BUFG clk:   all UART controllers, TX chain (CLKDIV), CDR
//                        pattern generator, PLL measurement system clock
//   CLK_RX (CDR, bank 34): BUFIO + BUFR /8 inside aio_cdr_blk
//   CLK_BIT_A, CLK60_A, REF_DIG (PLL, bank 35): BUFGs inside aio_pll_blk,
//   plus the BUFG of usb_clk_gen's clk60: 8 BUFGs in all.
// The shared SPI_SCK / SPI_SDI of the merged board are arbitrated by
// aio_spi_arb (aio_glue.v).
// AIO_SIM (Icarus): primitives from fpga/sim/prims_sim.v, TX_PISO_SIM for the
// behavioural TX serializer.
//-----------------------------------------------------------------------------
`timescale 1ns/1ps

module aio_fpga_top #(
    parameter integer BAUD     = 921600,
    parameter integer AW       = 13,          // RX capture depth 2^AW words
    parameter integer PLL_FW   = 14,
    parameter integer CDR_FW   = 20,
    parameter integer SETTLE_W = 16           // UART select settling, 2^SETTLE_W clk cycles
) (
    // ZedBoard
    input  wire       gclk,
    input  wire       btn_rst,
    input  wire [1:0] sw,
    output wire [7:0] led,
    input  wire       uart_rxd,
    output wire       uart_txd,

    // FMC: TX block
    output wire tx_in_p_p, tx_in_p_n,
    output wire tx_in_n_p, tx_in_n_n,
    output wire tx_en,
    output wire fs_oe,
    output wire fs_dat,
    output wire fs_se0,
    output wire fs_ls,
    output wire fs_suspnd,
    output wire dp_pullup_en,
    output wire hs_term_en,
    output wire pd_en0,
    output wire pd_en1,
    input  wire rxrcv,
    input  wire rxdp,
    input  wire rxdm,
    input  wire vbus_det,
    output wire tx_dac_cs_n,
    // FMC: shared SPI
    output wire spi_sck,
    output wire spi_sdi,
    // FMC: RX block
    input  wire rx_out_p, rx_out_n,
    input  wire squelch_a,
    input  wire disc_a,
    output wire rx_en,
    output wire rx_dac_cs_n,
    // FMC: PLL block
    input  wire clk_bit_a_p, clk_bit_a_n,
    input  wire clk60_a_p,   clk60_a_n,
    input  wire ref_dig,
    input  wire muxout,
    output wire adf_clk,
    output wire adf_data,
    output wire adf_le,
    output wire adf_ce,
    output wire pll_vco_off,
    output wire lf_dis,
    output wire ol_en,
    output wire cdcm_off,
    output wire pll_dac_cs_n,
    output wire pll_adc_cs_n,
    input  wire pll_adc_sdo,
    output wire refsrc0,
    output wire refsrc1,
    output wire oe24,
    output wire oe19,
    // FMC: CDR block
    input  wire clk_rx_p, clk_rx_n,
    input  wire hs_rxd_p, hs_rxd_n,
    output wire dpat_p,   dpat_n,
    output wire cdr_en,
    output wire cdr_set,
    output wire dsel0,
    output wire dsel1,
    output wire cdr_vco_off,
    output wire csw_ext,
    output wire csw_dac,
    output wire cdr_dac_cs_n,
    output wire cdr_adc_cs_n,
    input  wire cdr_adc_sdo
);

    // ---------------- clocking ----------------
    wire gclk_i, gclk_b, clkfb, c480_u, c240_u, c200_u, c60_u;
    wire clk480, clkdiv, clk240, clk200, clk, locked;
    IBUF u_ibg (.I(gclk), .O(gclk_i));
    BUFG u_bgg (.I(gclk_i), .O(gclk_b));       // Y9 (bank 13) -> MMCM in bank 34's region
    MMCME2_BASE #(
        .CLKIN1_PERIOD    (10.0),
        .CLKFBOUT_MULT_F  (12.0),               // VCO 1200 MHz
        .DIVCLK_DIVIDE    (1),
        .CLKOUT0_DIVIDE_F (2.5),                // 480 MHz
        .CLKOUT1_DIVIDE   (5),                  // 240 MHz
        .CLKOUT2_DIVIDE   (6),                  // 200 MHz
        .CLKOUT3_DIVIDE   (20)                  // 60 MHz
    ) u_mmcm (
        .CLKIN1(gclk_b), .CLKFBIN(clkfb), .CLKFBOUT(clkfb), .CLKFBOUTB(),
        .CLKOUT0(c480_u), .CLKOUT0B(), .CLKOUT1(c240_u), .CLKOUT1B(),
        .CLKOUT2(c200_u), .CLKOUT2B(), .CLKOUT3(c60_u), .CLKOUT3B(),
        .CLKOUT4(), .CLKOUT5(), .CLKOUT6(),
        .LOCKED(locked), .PWRDWN(1'b0), .RST(btn_rst));
    BUFIO u_bio480 (.I(c480_u), .O(clk480));
    BUFR #(.BUFR_DIVIDE("4"), .SIM_DEVICE("7SERIES")) u_bufr_rx (
        .I(c480_u), .O(clkdiv), .CE(1'b1), .CLR(~locked));
    BUFG u_bg240 (.I(c240_u), .O(clk240));
    BUFG u_bg200 (.I(c200_u), .O(clk200));
    BUFG u_bg60  (.I(c60_u),  .O(clk));

    // reset: asynchronous assert (MMCM unlocked), release synchronous to clk
    reg [3:0] rst_sh;
    always @(posedge clk or negedge locked)
        if (!locked) rst_sh <= 4'h0;
        else         rst_sh <= {rst_sh[2:0], ~btn_rst};
    wire rst_n = rst_sh[3];

    // one IDELAYCTRL for the RX sampler and the CDR capture (both bank 34)
    wire idly_rdy;
    IDELAYCTRL u_idlyctrl (.REFCLK(clk200), .RST(~locked), .RDY(idly_rdy));

    // ---------------- UART block select ----------------
    wire [1:0] sel;
    wire [3:0] rxd_k, txd_k;
    aio_uart_sel #(.SETTLE_W(SETTLE_W)) u_usel (
        .clk(clk), .rst_n(rst_n), .sw(sw), .uart_rxd(uart_rxd), .uart_txd(uart_txd),
        .sel(sel), .rxd_k(rxd_k), .txd_k(txd_k));

    // ---------------- shared SPI ----------------
    wire [3:0] gnt, act, cs_pin, sck_k, sdi_k;
    aio_spi_arb u_sarb (
        .clk(clk), .rst_n(rst_n), .act(act), .cs_pin(cs_pin), .sck(sck_k), .sdi(sdi_k),
        .gnt(gnt), .spi_sck(spi_sck), .spi_sdi(spi_sdi));

    // ---------------- blocks ----------------
    wire tx_led, rx_led, pll_led, cdr_led_alive, cdr_led_ok;

    aio_tx_blk #(.BAUD(BAUD)) u_tx (
        .clk60(clk), .clk240(clk240), .rst_n(rst_n), .locked(locked),
        .uart_rxd(rxd_k[0]), .uart_txd(txd_k[0]),
        .spi_gnt(gnt[0]), .spi_act(act[0]), .spi_cs(cs_pin[0]),
        .tx_in_p_p(tx_in_p_p), .tx_in_p_n(tx_in_p_n), .tx_in_n_p(tx_in_n_p), .tx_in_n_n(tx_in_n_n),
        .tx_en(tx_en), .fs_oe_a(fs_oe), .fs_dat_a(fs_dat), .fs_se0_a(fs_se0), .fs_ls_a(fs_ls),
        .fs_suspnd(fs_suspnd), .dp_pullup_en_a(dp_pullup_en), .hs_term_en_a(hs_term_en),
        .pd_en_a0(pd_en0), .pd_en_a1(pd_en1),
        .dac_cs_n(tx_dac_cs_n), .dac_sck(sck_k[0]), .dac_sdi(sdi_k[0]),
        .rxrcv_a(rxrcv), .rxdp_a(rxdp), .rxdm_a(rxdm), .vbus_det(vbus_det),
        .led_active(tx_led));

    aio_rx_blk #(.BAUD(BAUD), .AW(AW)) u_rx (
        .clk(clk), .clk480(clk480), .clkdiv(clkdiv), .rst_n(rst_n), .locked(locked),
        .idly_rdy(idly_rdy),
        .uart_rxd(rxd_k[1]), .uart_txd(txd_k[1]),
        .spi_gnt(gnt[1]), .spi_act(act[1]), .spi_cs(cs_pin[1]),
        .rx_out_p(rx_out_p), .rx_out_n(rx_out_n), .squelch_a(squelch_a), .disc_a(disc_a),
        .vbus_det(vbus_det), .rx_en(rx_en),
        .dac_cs_n(rx_dac_cs_n), .dac_sck(sck_k[1]), .dac_sdi(sdi_k[1]),
        .led_active(rx_led));

    aio_pll_blk #(.BAUD(BAUD), .FW(PLL_FW)) u_pll (
        .clk(clk), .rst_n(rst_n), .locked(locked),
        .uart_rxd(rxd_k[2]), .uart_txd(txd_k[2]),
        .spi_gnt(gnt[2]), .spi_act(act[2]), .spi_cs(cs_pin[2]),
        .clk_bit_a_p(clk_bit_a_p), .clk_bit_a_n(clk_bit_a_n),
        .clk60_a_p(clk60_a_p), .clk60_a_n(clk60_a_n), .ref_dig(ref_dig), .muxout(muxout),
        .adf_clk(adf_clk), .adf_data(adf_data), .adf_le(adf_le), .adf_ce(adf_ce),
        .vco_off(pll_vco_off), .lf_dis(lf_dis), .cdcm_off(cdcm_off), .ol_en(ol_en),
        .dac_cs_n(pll_dac_cs_n), .adc_cs_n(pll_adc_cs_n),
        .spi_sck(sck_k[2]), .spi_sdi(sdi_k[2]), .adc_sdo(pll_adc_sdo),
        .refsrc0(refsrc0), .refsrc1(refsrc1), .oe24(oe24), .oe19(oe19),
        .led_pll(pll_led));

    aio_cdr_blk #(.BAUD(BAUD), .FW(CDR_FW)) u_cdr (
        .clk(clk), .clk240(clk240), .rst_n(rst_n), .locked(locked), .idly_rdy(idly_rdy),
        .uart_rxd(rxd_k[3]), .uart_txd(txd_k[3]),
        .spi_gnt(gnt[3]), .spi_act(act[3]), .spi_cs(cs_pin[3]),
        .clk_rx_p(clk_rx_p), .clk_rx_n(clk_rx_n), .hs_rxd_p(hs_rxd_p), .hs_rxd_n(hs_rxd_n),
        .dpat_p(dpat_p), .dpat_n(dpat_n),
        .cdr_en(cdr_en), .cdr_set(cdr_set), .dsel0(dsel0), .dsel1(dsel1),
        .vco_off(cdr_vco_off), .csw_ext(csw_ext), .csw_dac(csw_dac),
        .dac_cs_n(cdr_dac_cs_n), .adc_cs_n(cdr_adc_cs_n),
        .spi_sck(sck_k[3]), .spi_sdi(sdi_k[3]), .adc_sdo(cdr_adc_sdo),
        .led_alive(cdr_led_alive), .led_ok(cdr_led_ok));

    assign led = {sel, cdr_led_ok, cdr_led_alive, pll_led, rx_led, tx_led, locked};

endmodule
