#!/usr/bin/env python3
"""run_sims.py - ngspice characterisation of the discrete USB 2.0 PLL board
(afe_pll on the PLL board)

Usage:  python3 AFE/Discrete/PLL/sim/run_sims.py [case-filter ...] [--force]
        (JOBS=n parallel runs; results in sim/results/<case>/, summary in
        sim/results/summary.json)

Circuit (schematic sheets 3 / 4, doc section 4):
  VCO     BFR93A Colpitts (Q3), base-coupled parallel tank: 10 nH LQW18 (L1),
          1.8 pF (C_P), 16 pF (C_S) in series with the 1SV305 varactor (D1),
          tuning through R_K = 2.2 kOhm; BFR93A common-emitter buffer (Q4) ->
          CDCM1804 IN (single-ended, IN- at VBB); 470 Ohm tap to the VCO SMA.
          VCO_OFF (2N7002 Q5) pulls the oscillator's base bias to ground.
  Loop    ADF4002 (behavioural: tri-state PFD, anti-backlash pulse 2.9 ns,
          charge pump +-ICP with the datasheet compliance 0.5 V .. VP - 0.5 V)
          -> passive filter C4 || (R2 + C3) on node VTUNE (CP pin) -> R_K ->
          varactor.  The feedback is the VCO divided by 2 in the CDCM1804 (Y1,
          240 MHz) and by N in the ADF4002, so the PFD compares f_vco / (2 N)
          with f_ref / R.  The VCO is a phase integrator here, with the tuning
          curve f(V) of the transistor-level vco_* cases (pwl), so the loop
          transient needs no 480 MHz time steps.

Cases
  vco_<T>_<vdd>   transistor-level VCO: f, amplitude at the CDCM1804 input and at
                  the tank vs. tuning voltage 0 .. 4.5 V (T = -40 / 27 / 85 C,
                  VCO supply 4.60 / 4.82 / 5.00 V)
  vcotol_<L>_<T>  L1 +-2 % at -40 / 85 C (tolerance of the range ends)
  vcostart        VCO_OFF 1 -> 0 -> 1: start-up and stop times
  loop_24         24 MHz, R = 1, N = 10 (N_eff = 20), ICP = 1.25 mA: lock from
                  VTUNE = 0, then PLL_EN = 0 for 6 us (loop-filter discharge),
                  relock
  loop_24_cold / loop_24_hot   the same with the -40 / 85 C tuning curve
  loop_24_slow    the same with the slowest VCO case (L +2 %, 85 C: 480 MHz at 3.48 V)
  loop_19         19.2 MHz, R = 2, N = 25 (PFD 9.6 MHz, N_eff = 50), ICP = 3.125 mA
  loop_26         26 MHz with the model's /20 (target 520 MHz): must not lock
  loop_26_fast    the same with the fastest VCO case (L -2 %, -40 C)
"""
import json
import os
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor, as_completed

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")
LIB = os.path.join(HERE, "models", "pll_models.lib")

# ---- component values (keep equal to the schematic / doc section 4) ----
VAL = dict(
    # VCO (sheet 4)
    RC1=22.0, RB1a=4.7e3, RB1b=4.7e3, RB2=6.8e3, RE1=270.0, C1=10e-12, C2=10e-12,
    Ccpl=3.3e-12, Cp=1.5e-12, Cs=16e-12, Rk=2.2e3, Cb2=1.5e-12,
    RB3=10e3, RB4=4.7e3, RE2=100.0, RC2=220.0, Rbb=2e3, Rtap=470.0,
    Rvco=10.0,                       # +5V_A -> +5V_VCO filter resistor
    # loop filter (sheet 3)
    C4=15e-12, R2=2.2e3, C3=1.5e-9,
    C_node=12e-12,                   # VTUNE node: CP pin 5 pF + MCP6001 6 pF + switch / pads
    C_k=24e-12,                      # varactor node at low frequency: C_S + C_V (3 V)
    R_dis=100.0,                     # discharge path (TS5A23166 Ron 0.9 Ohm + 100 Ohm)
    VP=4.5)                          # ADF4002 VP from U17 (LP5907-4.5): limits VTUNE
ICP_24, ICP_19 = 1.25e-3, 3.125e-3   # ADF4002 CPI = 001 / 100 with RSET = 5.1 kOhm
T_ABP = 2.9e-9                       # antibacklash pulse (ABP2/ABP1 = 00)
CP_MISMATCH = 0.02                   # ADF4002 sink / source matching (datasheet max)
TOL_LOCK = 0.08e-2                   # spec 4.3: +-0.08 % (afe_pll.va testbench criterion)
VT_PTS = [0.0, 0.25, 0.5, 1.0, 1.5, 2.0, 2.5, 3.0, 3.5, 4.0, 4.5, 4.75]
VDD_VCO = 5.0 - 18e-3 * VAL["Rvco"]  # 4.82 V: 5 V minus the 10 Ohm filter at ~18 mA


def fmt(v):
    return "%.6g" % v


# ---------------------------------------------------------------------------
# transistor-level VCO
# ---------------------------------------------------------------------------
def vco_netlist(c, out):
    V = VAL
    L = ["* discrete PLL board - VCO (Q3 / Q4) - generated by run_sims.py",
         ".include %s" % LIB,
         ".options temp=%g tnom=27 reltol=1e-4 method=gear maxord=2" % c["temp"],
         "VCC vcc 0 %g" % c["vdd"]]
    if c.get("start"):
        # VCO_OFF: 1 (0..50 ns), 0 (50 ns .. 1.05 us), 1 again; 2N7002 as a switch
        L += ["VOFF off 0 PWL(0 5 50n 5 52n 0 1.05u 0 1.052u 5)",
              "SQ5 x 0 off 0 swq5", ".model swq5 sw vt=2.1 vh=0.1 ron=3 roff=1e9",
              "CQ5 x 0 25p"]
        L.append("VT vt 0 %g" % c["vt"])
    else:
        L.append("VT vt 0 %g" % c["vt"])
    L += ["RC1 vcc c1 %s" % fmt(V["RC1"]), "CC1 c1 0 100p", "CC1b c1 0 10n",
          "RB1b vcc x %s" % fmt(V["RB1b"]), "RB1a x b1 %s" % fmt(V["RB1a"]),
          "RB2 b1 0 %s" % fmt(V["RB2"]),
          "XQ3 c1 b1 e1 BFR93A",
          "RE1 e1 0 %s" % fmt(V["RE1"]),
          "C1 b1 e1 %s" % fmt(V["C1"]), "C2 e1 0 %s" % fmt(V["C2"]),
          "Ccpl b1 t %s" % fmt(V["Ccpl"]),
          "XL1 t lg LQW18_10N%s" % ("_" + c["lk"] if c.get("lk") else ""), "Llg lg 0 0.3n",          # via to the ground plane
          "Cp t 0 %s" % fmt(V["Cp"] * c.get("cpk", 1.0)),
          "Cs t k %s" % fmt(V["Cs"]),
          "XD1 0 k SV305",
          "Rk vt k %s" % fmt(V["Rk"]),
          "Cpar t 0 0.4p",                                # pads / traces at the tank
          "Cb2 e1 b2 %s" % fmt(V["Cb2"]),
          "RB3 vcc b2 %s" % fmt(V["RB3"]), "RB4 b2 0 %s" % fmt(V["RB4"]),
          "XQ4 c2 b2 e2 BFR93A",
          "RE2 e2 0 %s" % fmt(V["RE2"]), "CE2 e2 0 100p",
          "RC2 vcc c2 %s" % fmt(V["RC2"]),
          "Cout c2 inp 100p", "Rbb inp vbb %s" % fmt(V["Rbb"]),
          "Cin inp 0 1.5p",                               # CDCM1804 IN 1 pF + pad
          "VBB vbb 0 2.0",                                # CDCM1804 VBB = VDD - 1.3 V
          "Rtap c2 sma %s" % fmt(V["Rtap"]), "Rsma sma 0 50"]
    if not c.get("start"):
        L.append("Ikick 0 t PULSE(0 1m 1n 0.2n 0.2n 0.5n 1)")
    tstop = c.get("tstop", 300e-9)
    L += [".tran 20p %g 0 20p" % tstop, ".control", "run",
          "wrdata %s v(inp) v(t) v(e1)" % out, ".endc", ".end"]
    return "\n".join(L)


def vco_measure(path, t0, t1):
    d = np.loadtxt(path)
    t, v, vt = d[:, 0], d[:, 1], d[:, 3]
    m = (t >= t0) & (t <= t1)
    t, v, vt = t[m], v[m], vt[m]
    pp = v.max() - v.min()
    if pp < 0.05:
        return 0.0, pp, vt.max() - vt.min()
    vm = 0.5 * (v.max() + v.min())
    s = np.where((v[:-1] < vm) & (v[1:] >= vm))[0]
    tc = t[s] + (vm - v[s]) / (v[s + 1] - v[s]) * (t[s + 1] - t[s])
    f = (len(tc) - 1) / (tc[-1] - tc[0]) if len(tc) > 4 else 0.0
    return f, pp, vt.max() - vt.min()


def run_ngspice(d, net):
    cir = os.path.join(d, "tb.cir")
    with open(cir, "w") as f:
        f.write(net)
    r = subprocess.run(["ngspice", "-b", cir], capture_output=True, text=True, cwd=d)
    with open(os.path.join(d, "log.txt"), "w") as f:
        f.write(r.stdout + r.stderr)
    return r.returncode


def case_vco(name, c):
    d = os.path.join(RES, name)
    os.makedirs(d, exist_ok=True)
    rows = []
    for vt in VT_PTS:
        cc = dict(c, vt=vt)
        out = os.path.join(d, "w.txt")
        run_ngspice(d, vco_netlist(cc, out))
        f, pp, ppt = vco_measure(out, 180e-9, 300e-9)
        rows.append(dict(vt=vt, f=f, vpp_in=pp, vpp_tank=ppt))
    os.remove(os.path.join(d, "w.txt"))
    res = dict(case=name, temp=c["temp"], vdd=c["vdd"], rows=rows)
    fs = [r["f"] for r in rows]
    vts = [r["vt"] for r in rows]
    res["f_min"] = fs[0]
    res["f_05"] = fs[vts.index(0.5)]
    res["f_45"] = fs[vts.index(4.5)]
    res["v480"] = float(np.interp(480e6, fs, vts)) if fs[-1] > 480e6 else None
    if res["v480"] is not None:
        k = np.gradient(np.array(fs), np.array(vts))
        res["kvco480"] = float(np.interp(res["v480"], vts, k))
    res["vpp_in_min"] = min(r["vpp_in"] for r in rows)
    return res


def case_vcostart(name, c):
    d = os.path.join(RES, name)
    os.makedirs(d, exist_ok=True)
    out = os.path.join(d, "wave.txt")
    run_ngspice(d, vco_netlist(dict(c, vt=3.15, start=True, tstop=1.6e-6), out))
    w = np.loadtxt(out)
    t, v = w[:, 0], w[:, 1]
    # envelope: p-p in sliding 10 ns windows
    tg = np.arange(0, 1.6e-6, 5e-9)
    env = []
    for a in tg:
        m = (t >= a) & (t < a + 10e-9)
        env.append(v[m].max() - v[m].min() if m.any() else 0)
    env = np.array(env)
    full = np.median(env[(tg > 0.8e-6) & (tg < 1.0e-6)])
    on = tg[(tg > 52e-9) & (env > 0.9 * full)]
    off = tg[(tg > 1.052e-6) & (env < 0.1 * full)]
    np.savetxt(os.path.join(d, "env.txt"), np.c_[tg, env])
    f, pp, _ = vco_measure(out, 0.8e-6, 1.0e-6)
    return dict(case=name, f=f, vpp_in=full,
                t_start=float(on[0] - 52e-9) if len(on) else None,
                t_stop=float(off[0] - 1.052e-6) if len(off) else None)


# ---------------------------------------------------------------------------
# PLL loop (behavioural ADF4002 + real filter + phase-integrating VCO)
# ---------------------------------------------------------------------------
def curve_of(case):
    p = os.path.join(RES, case, "result.json")
    with open(p) as f:
        rows = json.load(f)["rows"]
    return [(r["vt"], r["f"]) for r in rows if r["f"] > 0]


def loop_netlist(c, out):
    V = VAL
    cur = curve_of(c["curve"])
    # f(V) below 0 V / above 4.75 V: flat (varactor forward / the CP rail)
    pw = ", ".join("%g, %g" % (v, f / 1e6) for v, f in [(-1.0, cur[0][1])] + cur + [(6.0, cur[-1][1])])
    fpfd = c["fref"] / c["R"]
    neff = 2 * c["N"]
    L = ["* discrete PLL board - loop transient - generated by run_sims.py",
         ".options reltol=1e-4 abstol=1e-12 method=gear maxord=2",
         # reference after the R counter (square, 1 ns edges)
         "VREF ref 0 PULSE(0 1 %g 1n 1n %g %g)" % (2e-9, 0.5 / fpfd - 1e-9, 1 / fpfd),
         "Aref [ref] [refd] adc1",
         ".model adc1 adc_bridge(in_low=0.4 in_high=0.6)",
         # VCO phase in cycles (MHz * us): V(ph) = integral of f(V_k) dt
         "Bvco 0 ph I=pwl(V(k), %s) * V(en_v)" % pw,
         "Cph ph 0 1u",
         "Rph ph 0 1e12",
         # divider output: f_vco / neff, square via sin (smooth for the solver)
         "Bdiv dv 0 V=0.5 + 0.5 * sin(6.283185307 * V(ph) / %d)" % neff,
         "Adiv [dv] [divd] adc1",
         # tri-state PFD: two D flip-flops (D = 1), reset by AND(UP, DN) after T_ABP
         "Ahi hi pu1", ".model pu1 d_pullup",
         "Alo lo pd1", ".model pd1 d_pulldown",
         "Aup hi refd lo rst up upb dff1",
         "Adn hi divd lo rst dn dnb dff1",
         ".model dff1 d_dff(clk_delay=0.3n set_delay=0.3n reset_delay=0.3n)",
         "Aand [up dn] rst0 and1", ".model and1 d_and(rise_delay=%g fall_delay=0.3n)" % T_ABP,
         "Aenr [rst0 pdn] rst or1", ".model or1 d_or(rise_delay=0.1n fall_delay=0.1n)",
         "Aud [up dn] [upa dna] dac1",
         ".model dac1 dac_bridge(out_low=0 out_high=1 t_rise=0.3n t_fall=0.3n)",
         # PLL_EN (pdn = not PLL_EN): ADF4002 CE low -> PFD reset, CP three-state
         "Vpdn pdna 0 PWL(%s)" % c["pdn_pwl"],
         "Apdn [pdna] [pdn] adc1",
         "Ben en_v 0 V=1",
         # charge pump with compliance (datasheet: ICP within 1.5 % for 0.5 V .. VP - 0.5 V)
         # source 1 % high, sink 1 % low: the datasheet's 2 % sink / source matching
         "Bcp 0 vt I=%g * (%g * V(upa) * 0.5 * (1 + tanh((%g - 0.25 - V(vt)) / 0.08))"
         " - %g * V(dna) * 0.5 * (1 + tanh((V(vt) - 0.25) / 0.08)))"
         % (c["icp"], 1 + CP_MISMATCH / 2, V["VP"], 1 - CP_MISMATCH / 2),
         # loop filter: C4 || (R2 + C3) on VTUNE, node capacitance
         "C4 vt 0 %g" % (V["C4"] + V["C_node"]),
         "R2 vt z %g" % V["R2"], "C3 z 0 %g" % V["C3"],
         "Rleak vt 0 1e10",
         # varactor feed R_K and the varactor node
         "Rk vt k %g" % V["Rk"], "Ck k 0 %g" % V["C_k"],
         # LF_DIS switch (TS5A23166 + 100 Ohm) while PLL_EN = 0
         "Sdis vt 0 pdna 0 swd", ".model swd sw vt=0.5 vh=0.05 ron=%g roff=1e11" % V["R_dis"],
         ".ic v(vt)=0 v(z)=0 v(k)=0 v(ph)=0",
         ".tran 0.2n %g 0 0.5n uic" % c["tstop"],
         ".control", "run",
         "linearize v(vt) v(k)",
         "wrdata %s v(vt) v(k)" % out,
         ".endc", ".end"]
    return "\n".join(L)


def fvco(curve, vk):
    vs, fs = zip(*curve)
    return np.interp(vk, vs, fs)


def case_loop(name, c):
    d = os.path.join(RES, name)
    os.makedirs(d, exist_ok=True)
    out = os.path.join(d, "wave.txt")
    rc = run_ngspice(d, loop_netlist(c, out))
    w = np.loadtxt(out)
    t, vt, vk = w[:, 0], w[:, 1], w[:, 3]
    cur = curve_of(c["curve"])
    f = fvco(cur, vk)
    # decimate the stored wave (every 2 ns) for the figures
    tg = np.arange(0, t[-1], 2e-9)
    np.savetxt(out, np.c_[tg, np.interp(tg, t, vt), np.interp(tg, t, vk), np.interp(tg, t, f)],
               fmt="%.5e")
    res = dict(case=name, rc=rc, fref=c["fref"], R=c["R"], N=c["N"], icp=c["icp"], curve=c["curve"])
    target = c["fref"] / c["R"] * 2 * c["N"]
    res["target"] = target

    def settle(ta, tb):
        m = (t >= ta) & (t <= tb)
        tt, ff = t[m], f[m]
        bad = np.abs(ff / target - 1) > TOL_LOCK
        if bad[-1]:
            return None
        idx = np.where(bad)[0]
        return float(tt[idx[-1] + 1] - ta) if len(idx) else 0.0

    if c.get("nolock"):
        m = t > c["tstop"] - 5e-6
        res["f_end"] = float(f[m].mean())
        res["vt_end"] = float(vt[m].mean())
        res["locked"] = bool(np.all(np.abs(f[m] / target - 1) < TOL_LOCK))
        return res
    t_off, t_on = c["t_off"], c["t_on"]
    res["t_lock1"] = settle(0, t_off)
    m = (t > t_off - 3e-6) & (t < t_off)
    res["vt_lock"] = float(vt[m].mean())
    res["f_lock_ppm"] = float((f[m].mean() / target - 1) * 1e6)
    # ripple on VTUNE / varactor node in lock (reference feed-through)
    res["vt_ripple_mv"] = float((vt[m].max() - vt[m].min()) * 1e3)
    res["vk_ripple_mv"] = float((vk[m].max() - vk[m].min()) * 1e3)
    # deterministic period modulation from the varactor ripple: df = Kvco * dV
    vs, fs = zip(*cur)
    kv = float(np.interp(res["vt_lock"], vs, np.gradient(np.array(fs), np.array(vs))))
    res["kvco"] = kv
    res["df_ripple_ppm"] = float(kv * res["vk_ripple_mv"] * 1e-3 / target * 1e6)
    # reference spur: amplitude A of the f_pfd component on the varactor node,
    # narrow-band FM: spur = 20 log10(Kvco A / (2 f_pfd)) dBc
    fp = c["fref"] / c["R"]
    tu = np.arange(t_off - 2e-6, t_off, 0.1e-9)
    n_per = int(round(1 / (fp * 0.1e-9)))
    tu = tu[: (len(tu) // n_per) * n_per]
    vu = np.interp(tu, t, vk)
    ph = np.exp(-2j * np.pi * fp * tu)
    a1 = 2 * abs(np.mean((vu - vu.mean()) * ph))
    res["vk_fpfd_uv"] = float(a1 * 1e6)
    res["spur_dbc"] = float(20 * np.log10(max(kv * a1 / (2 * fp), 1e-12)))
    # discharge while PLL_EN = 0
    m = (t > t_off) & (t < t_on)
    lo = np.where(vt[m] < 0.05)[0]
    res["t_dis_50mv"] = float(t[m][lo[0]] - t_off) if len(lo) else None
    res["vt_at_enable"] = float(np.interp(t_on, t, vt))
    res["t_lock2"] = settle(t_on, c["tstop"])
    # overshoot of the first lock
    m = (t > 0) & (t < t_off)
    res["f_peak"] = float(f[m].max())
    return res


