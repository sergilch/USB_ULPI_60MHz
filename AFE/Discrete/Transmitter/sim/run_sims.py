def static_case(cfg):
    """Bits (per UI, from t0 = 20 ns): 40 UI off (idle J clamp), 100 UI J with TX_EN,
    100 UI K, 60 UI P=N=1, 60 UI P=N=0, then 60 UI J and TX_EN off."""
    p = [1] * 140 + [0] * 100 + [1] * 60 + [0] * 60 + [1] * 120
    n = [0] * 140 + [1] * 100 + [1] * 60 + [0] * 60 + [0] * 120
    en = [0] * 40 + [1] * 380 + [0] * 60
    c = dict(cfg, p_bits=p, n_bits=n, en_bits=en, t_stop=20e-9 + len(p) * UI, tstep=10e-12)
    return c


def eval_static(w, vdd):
    t0 = 20e-9
    T = lambda ui: t0 + ui * UI  # noqa: E731
    dif = lambda t: at(w, "np", t) - at(w, "nm", t)  # noqa: E731
    r = {}
    r["idle_leak_uA"] = 1e6 * max(abs(at(w, "ip", T(35))), abs(at(w, "in", T(35))))
    r["i_dump_mA"] = 1e3 * at(w, "id", T(35))
    r["i_p_J_mA"] = 1e3 * at(w, "ip", T(135))
    r["i_n_J_uA"] = 1e6 * at(w, "in", T(135))
    r["vJ_mV"] = 1e3 * dif(T(135))
    r["vK_mV"] = 1e3 * dif(T(235))
    r["dp_J_mV"] = 1e3 * at(w, "np", T(135))
    r["pn11_dp_mV"] = 1e3 * at(w, "np", T(295))
    r["pn11_dm_mV"] = 1e3 * at(w, "nm", T(295))
    r["pn00_dp_mV"] = 1e3 * at(w, "np", T(355))
    r["pn00_dm_mV"] = 1e3 * at(w, "nm", T(355))
    r["v_ne_on_V"] = at(w, "ne", T(135))
    r["v_et_V"] = at(w, "et", T(135))
    r["tail_vec_V"] = r["v_et_V"] - r["v_ne_on_V"]
    r["v_ne_off_V"] = at(w, "ne", T(35))
    r["veb_rev_max_V"] = float(np.max(np.maximum(w["bp"], w["bn"]) - w["ne"]))
    # t_en: TX_EN pin crossing vdd/2 -> |DP-DM| at the near end within 90 % of the J level
    t = w["t"]
    ten_pin = cross(t, w["en"], vdd / 2, T(39), rising=True)[0]
    d = w["np"] - w["nm"]
    lvl = r["vJ_mV"] / 1e3
    m = (t > ten_pin) & (t < T(130))
    ok = np.where(m & (d > 0.9 * lvl))[0]
    r["t_en_ns"] = 1e9 * (t[ok[0]] - ten_pin) if len(ok) else None
    toff_pin = cross(t, w["en"], vdd / 2, T(419), rising=False)[0]
    m = (t > toff_pin)
    ok = np.where(m & (np.abs(d) < 0.1 * lvl))[0]
    r["t_dis_ns"] = 1e9 * (t[ok[0]] - toff_pin) if len(ok) else None
    return r


def chirp_case(cfg):
    p = [0] * 300
    n = [1] * 300
    en = [0] * 20 + [1] * 280
    return dict(cfg, near_term=False, pullup=True, p_bits=p, n_bits=n, en_bits=en,
                t_stop=20e-9 + 300 * UI, tstep=20e-12)


def eye_case(cfg):
    line = usbpat.hs_packet_line()
    lead = 16                                   # TX_LEAD (J while the enable settles)
    p = [1] * (20 + lead) + line + [line[-1]] * 4 + [1] * 20
    n = [1 - b for b in p]
    en = [0] * 20 + [1] * (lead + len(line) + 4) + [0] * 20
    c = dict(cfg, p_bits=p, n_bits=n, en_bits=en, t_stop=20e-9 + len(p) * UI, tstep=5e-12)
    c["line"] = line
    c["first_ui"] = 20 + lead
    return c


def eval_eye(w, c, node=("fp", "fm")):
    """Eye of the packet (SYNC .. last data bit) at the given node pair."""
    t = w["t"]
    d = w[node[0]] - w[node[1]]
    t0 = 20e-9 + c["first_ui"] * UI
    nb = len(c["line"]) - 8
    tend = t0 + nb * UI
    # delay: first SYNC edge (J -> K) at the node vs. the LVPECL source edge (t0 + T_EDGE/2)
    # first SYNC edge: the first J -> K (falling) zero crossing after the lead
    # (while the driver is off the difference sits at 0 V and crosses it on noise)
    z0 = cross(t, d, 0.0, t0 - UI / 2, rising=False)[0]
    zc = [z0] + [z for z in cross(t, d, 0.0, z0 + 1e-12) if z0 + 1e-12 < z < tend + 3 * UI]
    delay = zc[0] - (t0 + T_EDGE / 2)
    ph = np.array([(z - t0 - delay - T_EDGE / 2) % UI for z in zc[1:]])
    ph = np.where(ph > UI / 2, ph - UI, ph)
    jit_pp = float(ph.max() - ph.min()) if len(ph) else 0.0
    # sample every bit at the eye centre (+UI/2 from the expected crossing)
    vs, hi, lo = [], [], []
    for i in range(nb):
        ts = t0 + delay + T_EDGE / 2 + (i + 0.5) * UI
        v = float(np.interp(ts, t, d))
        (hi if c["line"][i] else lo).append(v)
    # eye width at 0 V: worst crossing spread; eye height at centre
    eh = min(hi) - max(lo)
    # 10-90 % edge times on edges preceded and followed by >= 2 equal bits
    lvl_j, lvl_k = float(np.median(hi)), float(np.median(lo))
    rts, fts = [], []
    L = c["line"]
    for i in range(2, nb - 2):
        if L[i - 2] == L[i - 1] and L[i] == L[i + 1] and L[i] != L[i - 1]:
            te = t0 + delay + T_EDGE / 2 + i * UI
            m = (t > te - UI) & (t < te + UI)
            tt, dd = t[m], d[m]
            a = lvl_k + 0.1 * (lvl_j - lvl_k)
            b = lvl_k + 0.9 * (lvl_j - lvl_k)
            rising = L[i] == 1
            ca = cross(tt, dd, a, rising=rising)
            cb = cross(tt, dd, b, rising=rising)
            if ca and cb:
                (rts if rising else fts).append(abs(cb[0] - ca[0]))
    return dict(delay_ns=1e9 * delay, jitter_pp_ps=1e12 * jit_pp, eye_height_mV=1e3 * eh,
                vJ_mV=1e3 * lvl_j, vK_mV=1e3 * lvl_k,
                vJ_min_mV=1e3 * min(hi), vK_max_mV=1e3 * max(lo),
                rise_ps=1e12 * float(np.mean(rts)) if rts else None,
                fall_ps=1e12 * float(np.mean(fts)) if fts else None,
                eye_width_ps=1e12 * (UI - jit_pp))


def trim_dc(model="BFT92"):
    """DC sweep of V_CTL with TX_IN_P = 1, TX_EN = 1 (operating point per value)."""
    d = os.path.join(RES, "trim")
    os.makedirs(d, exist_ok=True)
    c = base_cfg(model)
    c.update(p_bits=[1, 1], n_bits=[0, 0], en_bits=[1, 1], t_stop=1e-9, out=os.path.join(d, "dc.txt"))
    net = netlist(c)
    net = net.replace("VCTL vctl 0 0.6", "VCTL vctl 0 DC 0.6")
    # .dc evaluates a one-point PWL as 0 V: use plain DC sources for the bit inputs
    net = re.sub(r"PWL\(\s*0\.0000e\+00\s+(-?[\d.]+)\)", r"DC \1", net)
    net = net.replace(".tran 5e-12 1e-09 0 5e-12", ".dc VCTL 0.30 0.90 0.01")
    net = net.replace("wrdata %s" % c["out"], "wrdata %s" % c["out"])
    open(os.path.join(d, "tb.cir"), "w").write(net)
    r = subprocess.run(["ngspice", "-b", os.path.join(d, "tb.cir")], capture_output=True, text=True)
    open(os.path.join(d, "log.txt"), "w").write(r.stdout + r.stderr)
    w = np.loadtxt(c["out"], skiprows=1)
    vctl, ip, vnp, vnm = w[:, 0], w[:, 7], w[:, 1], w[:, 2]
    ideal = vctl * VAL["Rr"] / (VAL["Rg"] * VAL["Rs"])            # tail current
    return dict(vctl=vctl.tolist(), i_mA=(1e3 * ip).tolist(), tail_mA=(1e3 * ideal).tolist(),
                vdiff_mV=(1e3 * (vnp - vnm)).tolist(),
                alpha_min=float(np.min(ip / ideal)), alpha_max=float(np.max(ip / ideal)),
                lin_err_pct=float(np.max(np.abs(ip / ideal / np.mean(ip / ideal) - 1)) * 100))


