#!/usr/bin/env python3
"""run_sims.py - ngspice characterisation of the discrete HS transmitter core

Usage:  python3 AFE/Discrete/Transmitter/sim/run_sims.py [case-filter ...]
        (JOBS=n for parallel runs; results in sim/results/<case>/, summary in
        sim/results/summary.json)

The circuit is the HS part of the transmitter board (schematic sheet 3, doc
section 5): regulated tail current source (MCP6V02 + MMBT3906, Rs), bias
current generator (MCP6V02 + MMBT3904, Rg, Rr), PNP current-steering triple
(Q_P -> DP, Q_N -> DM, Q_D dump), LVPECL base drive from SN65LVDT101, TX_EN
dump-base divider, RB751S40 collector blocking diodes, FSUSB42 HS termination
path, board trace, USBLC6 ESD, cable and the far-end (host) 45 Ohm terminations.

Cases
  static   TX_EN off -> on, J, K, P=N=1, P=N=0     levels, t_en, leakage
  chirp    near-end termination off, pull-up on, K  device chirp level
  eye      USB 2.0 Test_Packet at 480 Mb/s           eye, edges, delay, jitter
  trim     DC sweep of V_CTL 0.30 .. 0.90 V          i_hs linearity (TX_AMP / TX_VREF / TX_I_5U)
  corner   eye + static for {BFT92, MMBTH81} x VDD {3.135, 3.3, 3.465} x T {-40, 27, 85}
"""
