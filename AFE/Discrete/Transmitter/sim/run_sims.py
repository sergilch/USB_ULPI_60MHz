T_EDGE = 200e-12                 # LVPECL edge, 0-100 % (SN65LVDT101: tr 20-80 % <= 220 ps)

# ---- component values (keep equal to the schematic / doc section 5) ----
VAL = dict(Rs=15.0, Rr=1690.0, Rg=3570.0,           # I_tail = Vctl*Rr/(Rg*Rs) = 18.94 mA @ 0.6 V
                                                    # (BFT92 beta ~34: ~94 % reaches DP/DM -> 17.8 mA)
           Ra=237.0, Rb=255.0, Rc=549.0,             # dump base: 0.60 V (TX_EN=0) / 2.00 V (TX_EN=1)
           Rtu=130.0, Rtd=82.0,                      # LVPECL Thevenin termination: 50.3 Ohm to 1.28 V = VCC - 2 V
           Rterm=40.2, Ron=4.5,                      # FSUSB42 + termination resistor = 44.7 Ohm
           Rhost=45.0, Rpu=1500.0)


def pwl(name, n1, n2, bits, t0, lo, hi, tr=T_EDGE, skew=0.0, init=None):
    """PWL voltage source from a bit list (one value per UI, starting at t0)."""
    pts = []
    prev = bits[0] if init is None else init
    pts.append((0.0, prev))
    for i, b in enumerate(bits):
        t = t0 + i * UI + skew
        if b != prev:
            pts.append((t, prev))
            pts.append((t + tr, b))
            prev = b
    v = lambda x: lo + (hi - lo) * x  # noqa: E731
    body = " ".join("%.4e %.4f" % (t, v(x)) for t, x in pts)
    lines, cur = [], "%s %s %s PWL(" % (name, n1, n2)
    for tok in body.split(" "):
        if len(cur) > 100:
            lines.append(cur)
            cur = "+"
        cur += " " + tok
    lines.append(cur + ")")
    return "\n".join(lines)


def tline(name, a, b, c, d, z0, td):
    """Lossless line as LTRA (ngspice's T element stalls on breakpoint pile-up here)."""
    return ["O%s %s 0 %s 0 lt_%s" % (name, a, c, name),
            ".model lt_%s ltra r=0 g=0 l=%g c=%g len=1" % (name, z0 * td, td / z0)]


def netlist(c):
    """c: dict with model, vdd, temp, vctl, near_term, pullup, p_bits, n_bits,
    en_bits (one value per UI), t_stop, tstep, outputs."""
    V = VAL
    vdd = c["vdd"]
    voh, vol = vdd - 1.02, vdd - 1.61        # SN65LVDT101 typ, 50 Ohm to VCC - 2 V
    q = c["model"]
    # bases are driven by the inverting output: TX_IN_P = 1 -> base low -> Q_P on
    bp = [1 - b for b in c["p_bits"]]
    bn = [1 - b for b in c["n_bits"]]
    t0 = 20e-9
    L = []
    L.append("* discrete USB HS transmitter core - generated by run_sims.py")
    L.append(".include %s" % LIB)
    L.append(".model RB751S40 D (is=8n n=1.03 rs=3.5 cjo=2.6p vj=0.35 m=0.45 bv=40 ibv=10u eg=0.69 xti=2)")
    L.append(".options temp=%g tnom=27 reltol=1e-4 method=trap" % c["temp"])
    L.append("VDD vdd 0 %g" % vdd)
    # ---- bias: V_CTL -> I_CTL (U1B, Q_G, Rg) -> drop on Rr ----
    L.append("VCTL vctl 0 %g" % c["vctl"])
    L.append("XU1B vctl eg og vdd opamp_rr")
    L.append("RBG og bg 1k")
    L.append("QG vrefn bg eg Q2N3904")
    L.append("RG eg 0 %g" % V["Rg"])
    L.append("RR vdd vrefn %g" % V["Rr"])
    L.append("CR vdd vrefn 100n")
    # ---- tail: U1A forces V(Rs) = V(Rr) ----
    L.append("XU1A vrefn et ot vdd opamp_rr")
    L.append("RBT ot bt 1k")
    L.append("CBT bt vdd 10n")
    L.append("RS vdd et %g" % V["Rs"])
    L.append("QT nem bt et Q2N3906")
    L.append("CNE nem 0 0.5p")
    # ---- steering triple (SOT-23 leads: 0.8 nH emitter/collector) ----
    L.append("QP cp bpq nem %s" % q)
    L.append("QN cn bnq nem %s" % q)
    L.append("QD cd bdi nem %s" % q)
    L.append("VIP cp cpl 0")
    L.append("VIN cn cnl 0")
    L.append("VID cd 0 0")
    L.append("CCP cpl 0 0.15p")
    L.append("CCN cnl 0 0.15p")
    # RB751S40 collector blocking diodes (D17 / D18): keep the collector-base junction from
    # clamping DP / DM while the FS/LS driver or the pull-up holds the wire high and the
    # bases sit at the LVPECL levels (FS/LS idle: TX_IN_P = 1 -> Q_P base 1.69 V)
    if c.get("hs_diode", True):
        L.append("DBP cpl cpk RB751S40")
        L.append("DBN cnl cnk RB751S40")
    else:
        L.append("VBP cpl cpk 0")
        L.append("VBN cnl cnk 0")
    L.append("LCP cpk dpi 0.8n")
    L.append("RLCP cpk dpi 50")
    L.append("RLCN cnk dmi 50")
    L.append("LCN cnk dmi 0.8n")
    # ---- LVPECL drive (Y/Z of SN65LVDT101, 7 Ohm source), Thevenin termination at the base ----
    for nm, bits in (("p", bp), ("n", bn)):
        L.append(pwl("VPE%s" % nm, "pe%s" % nm, "0", bits, t0, vol, voh,
                     skew=c.get("skew_" + nm, 0.0)))
        L.append("RPE%s pe%s b%sx 7" % (nm, nm, nm))
        L += tline("PE" + nm, "b%sx" % nm, 0, "b%si" % nm, 0, 50.0, 60e-12)
        L.append("RTU%s vdd b%si %g" % (nm, nm, V["Rtu"]))
        L.append("RTD%s b%si 0 %g" % (nm, nm, V["Rtd"]))
        L.append("RBS%s b%si b%sq %g" % (nm, nm, nm, c["rbase"]))   # base stopper / edge rate
    # ---- TX_EN: SN74LVC1T45 output (25 Ohm, 1 ns edges) -> Ra/Rb/Rc divider -> Q_D base ----
    L.append(pwl("VEN", "en", "0", c["en_bits"], t0, 0.0, vdd, tr=1e-9))
    L.append("REN en en3 25")
    L.append("RA en3 bdi %g" % V["Ra"])
    L.append("RB bdi 0 %g" % V["Rb"])
    L.append("RC vdd bdi %g" % V["Rc"])
    L.append("CBD bdi 0 1p")
    # ---- per wire: driver node -> FSUSB42 (D) -> 2D: Rterm (HS) | off (chirp: OE# high)
    #      -> 25 mm trace (45 Ohm) -> USBLC6 + connector -> 0.5 m cable -> host 45 Ohm ----
    for w in ("p", "m"):
        d = "d%si" % w
        L.append("CD%s %s 0 1.0p" % (w, d))                       # pad + collector routing
        if c.get("tx_cap", 0) > 0:                                # TX_CAP_P/N: edge-rate capacitor
            L.append("RCAP%s %s xc%s 0.5" % (w, d, w))                # (C0G 0402 ESR + via)
            L.append("CCAP%s xc%s 0 %g" % (w, w, c["tx_cap"]))
        L.append("CSW%s %s 0 1.9p" % (w, d))                      # FSUSB42 D side (C_ON 3.7 pF split)
        L.append("RRX%s %s rx%s 1k" % (w, d, w))                  # FS/LS receivers behind R55 / R56
        L.append("CRX%s rx%s 0 4p" % (w, w))
        if c["near_term"]:
            L.append("RON%s %s s2%s %g" % (w, d, w, V["Ron"]))
            L.append("CS2%s s2%s 0 1.8p" % (w, w))
            L.append("RTM%s s2%s 0 %g" % (w, w, V["Rterm"]))
        # else: chirp (HS_TERM_EN = 0, FS_OE = 0): FSUSB42 OE# = NOR(FS_OE, HS_TERM_EN) = 1,
        # both ports off, the FS/LS driver is not on the line
        L += tline("TR" + w, d, 0, "n" + w, 0, 45.0, c.get("trace_td", 50e-12))  # 8 mm board trace
        L.append("CESD%s n%s 0 2.5p" % (w, w))                     # USBLC6-2SC6 + connector
        L += tline("CB" + w, "n" + w, 0, "f" + w, 0, 45.0, 2.5e-9)    # 0.5 m cable
        L.append("CHST%s f%s 0 2p" % (w, w))
        if c.get("far_term", True):
            L.append("RHST%s f%s 0 %g" % (w, w, V["Rhost"]))
        else:
            L.append("RHST%s f%s 0 15k" % (w, w))
    if c["pullup"]:
        L.append("RPU vdd np %g" % V["Rpu"])
    L.append(".tran %g %g 0 %g" % (c.get("tstep", 5e-12), c["t_stop"], c.get("tstep", 5e-12)))
    L.append(".control")
    L.append("set wr_singlescale")
    L.append("set wr_vecnames")
    L.append("option numdgt=7")
    L.append("run")
    L.append("wrdata %s v(np) v(nm) v(fp) v(fm) v(dpi) v(dmi) i(vip) i(vin) i(vid) "
             "v(nem) v(et) v(bpi) v(bni) v(bdi) v(en)" % c["out"])
    L.append("quit")
    L.append(".endc")
    L.append(".end")
    return "\n".join(L) + "\n"


