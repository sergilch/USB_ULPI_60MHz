def task_list():
    """(name, config, kind) of every case."""
    T = []
    for model in ("BFT92", "MMBTH81"):
        cfg = base_cfg(model)
        T.append(("static_%s" % model, static_case(cfg), "static"))
        T.append(("chirp_%s" % model, chirp_case(cfg), "chirp"))
        T.append(("eye_%s" % model, eye_case(cfg), "eye"))
        for vdd in (3.135, 3.465):
            for temp in (-40, 85):
                cfg = base_cfg(model, vdd, temp)
                tag = "%s_%g_%g" % (model, vdd, temp)
                T.append(("corner_static_" + tag, static_case(cfg), "static"))
                T.append(("corner_eye_" + tag, eye_case(cfg), "eye"))
    for model in ("BFT92", "MMBTH81"):
        for rb, cap in ((10.0, 0.0), (22.0, 0.0), (33.0, 0.0), (47.0, 0.0), (47.0, 3.3e-12),
                        (68.0, 3.3e-12), (68.0, 4.7e-12), (68.0, 6.8e-12), (100.0, 3.3e-12),
                        (100.0, 4.7e-12)):
            if True:
                c = eye_case(base_cfg(model, tx_cap=cap, rbase=rb))
                T.append(("rb_%s_%g_%gp" % (model, rb, cap * 1e12), c, "eye"))
    sk = eye_case(base_cfg("BFT92"))
    sk["skew_n"] = 150e-12                                      # TX_IN_N 150 ps late
    T.append(("skew_BFT92", sk, "eye"))
    return T


def evaluate(name, c, kind, w):
    if kind == "static":
        r = eval_static(w, c["vdd"])
    elif kind == "chirp":
        r = dict(dm_mV=1e3 * at(w, "nm", w["t"][-1]), dp_mV=1e3 * at(w, "np", w["t"][-1]),
                 dm_minus_dp_mV=1e3 * (at(w, "nm", w["t"][-1]) - at(w, "np", w["t"][-1])))
    else:
        r = dict(far=eval_eye(w, c, ("fp", "fm")), near=eval_eye(w, c, ("np", "nm")))
    r.update(model=c["model"], vdd=c["vdd"], temp=c["temp"], tx_cap_pF=c.get("tx_cap", 0) * 1e12,
             rbase=c["rbase"])
    return r


def load_wave(name):
    w = np.loadtxt(os.path.join(RES, name, "wave.txt"), skiprows=1)
    return {k: w[:, i] for i, k in enumerate(COLS)}


def main():
    args = sys.argv[1:]
    reev = "--reeval" in args
    flt = [a for a in args if a not in ("--reeval", "--force")]
    want = lambda n: not flt or any(f in n for f in flt)  # noqa: E731
    os.makedirs(RES, exist_ok=True)
    sp = os.path.join(RES, "summary.json")
    summary = json.load(open(sp)) if os.path.exists(sp) else {}
    jobs = int(os.environ.get("JOBS", os.cpu_count() or 4))
    tasks = [t for t in task_list() if want(t[0])]

    def work(t):
        name, c, kind = t
        if reev:
            if not os.path.exists(os.path.join(RES, name, "wave.txt")):
                return name, None
            w = load_wave(name)
        else:
            if name in summary and "error" not in summary[name] and "--force" not in args:
                return name, summary[name]              # already simulated
            try:
                w = run_case(name, c)
            except RuntimeError as e:
                print("%-34s FAILED %s" % (name, e), flush=True)
                return name, dict(error=str(e))
        try:
            r = evaluate(name, c, kind, w)
        except Exception as e:                       # keep the other cases
            r = dict(error=repr(e))
        print("%-34s %s" % (name, json.dumps(r)[:220]), flush=True)
        wf = os.path.join(RES, name, "wave.txt")
        if not reev and not name.startswith(KEEP_WAVE) and os.path.exists(wf):
            os.remove(wf)                            # waves are 20 .. 100 MB each
        return name, r

    with ThreadPoolExecutor(1 if reev else jobs) as ex:
        for name, r in ex.map(work, tasks):
            if r is not None:
                summary[name] = r
            json.dump(summary, open(sp, "w"), indent=1)       # after every case
    if want("trim") and not reev:
        summary["trim"] = trim_dc()
        print("trim: linearity %.3f %%" % summary["trim"]["lin_err_pct"])
        json.dump(summary, open(sp, "w"), indent=1)


if __name__ == "__main__":
    main()
