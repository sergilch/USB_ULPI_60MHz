def run_case(name, c):
    d = os.path.join(RES, name)
    os.makedirs(d, exist_ok=True)
    c = dict(c)
    c["out"] = os.path.join(d, "wave.txt")
    cir = os.path.join(d, "tb.cir")
    base = netlist(c)
    # solver ladder: ngspice occasionally collapses the timestep at the BFT92's
    # internal collector node; retry with other integration settings
    for opt in SOLVER_OPTS:
        open(cir, "w").write(base.replace("reltol=1e-4 method=trap", opt))
        if os.path.exists(c["out"]):
            os.remove(c["out"])
        r = subprocess.run(["ngspice", "-b", cir], capture_output=True, text=True, timeout=3600)
        open(os.path.join(d, "log.txt"), "w").write(r.stdout + r.stderr)
        if os.path.exists(c["out"]) and "Timestep too small" not in r.stdout + r.stderr:
            break
    else:
        raise RuntimeError("%s: ngspice failed with every solver setting, see %s" % (name, d))
    w = np.loadtxt(c["out"], skiprows=1)
    cols = ["t", "np", "nm", "fp", "fm", "dpi", "dmi", "ip", "in", "id", "ne", "et",
            "bp", "bn", "bd", "en"]
    return {k: w[:, i] for i, k in enumerate(cols)}


def at(w, k, t):
    return float(np.interp(t, w["t"], w[k]))


def cross(t, y, lvl, t_from=0.0, rising=None):
    """All crossing times of y through lvl after t_from (linear interpolation)."""
    s = y - lvl
    idx = np.where((s[:-1] * s[1:] < 0) & (t[:-1] >= t_from))[0]
    out = []
    for i in idx:
        if rising is not None and (s[i + 1] > s[i]) != rising:
            continue
        out.append(t[i] - s[i] * (t[i + 1] - t[i]) / (s[i + 1] - s[i]))
    return out


