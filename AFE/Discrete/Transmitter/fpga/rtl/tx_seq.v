//-----------------------------------------------------------------------------
// tx_seq.v - packet / pattern sequencer of the transmitter-board FPGA
//
//   tx_seq --bytes (ready/valid)--> usb_tx_path --> usb_afe_tx_if8 --> tx_piso_7s
//
// Plays the role of the ULPI link + usb_tx_sync_mux for the board tests: it
// builds the byte stream of one packet (SYNC unless suppressed, then the body)
// for usb_tx_path and latches the per-packet controls (speed, bypass_en,
// eop_dis, lead_first) for usb_tx_path / usb_afe_tx_if8.
//
// Patterns (pattern[2:0], sampled at the packet start)
//   0  Test_Packet   USB 2.0 7.1.20: DATA0 PID, 53 bytes, CRC16 (56 bytes ROM)
//   1  user buffer   len bytes (1..64) from the 64-byte buffer, sent verbatim
//                    (PID and CRC included by the user)
//   2  Test_J        bypass (no NRZI / stuffing), no SYNC, no EOP: len bytes FFh
//   3  Test_K        as Test_J with 00h
//   4  chirp K       as Test_K (device chirp: HS driver into the host's 45 Ohm,
//                    pull-up on, near-end termination off - set in the TERM register);
//                    len = 60000 gives 1.0 ms
//   5  PRBS7         DATA0 PID, len payload bytes of PRBS7 (x^7 + x^6 + 1), CRC16
//   6, 7             as 0
// Patterns 2..4 use lead_first = 1 (usb_afe_tx_if8: TX_IN shows the first
// data bit during the TX_EN lead, so a chirp K never starts with a J).
//
// Sequencing: a rising edge of go starts a packet; with rpt = 1 packets repeat
// while go stays high, each one gap clk60 ticks after the previous packet has
// left usb_tx_path (busy low).  pkt_cnt counts finished packets.
//
// Clock clk60, reset rst_n asynchronous.
//-----------------------------------------------------------------------------
`timescale 1ns/1ps

module tx_seq (
    input  wire        clk60,
    input  wire        rst_n,

    // configuration (static while a sequence runs)
    input  wire        go,
    input  wire        rpt,
    input  wire [2:0]  pattern,
    input  wire [1:0]  speed_cfg,
    input  wire        sync_dis_cfg,
    input  wire [15:0] len,
    input  wire [15:0] gap,

    // user buffer write port
    input  wire        buf_we,
    input  wire [5:0]  buf_waddr,
    input  wire [7:0]  buf_wdata,

    // to usb_tx_path / usb_afe_tx_if8
    output reg  [1:0]  speed,
    output reg         bypass_en,
    output reg         eop_dis,
    output reg         lead_first,
    output reg         in_valid,
    output reg  [7:0]  in_data,
    output reg         in_last,
    input  wire        in_ready,
    input  wire        path_busy,

    output wire        seq_busy,
    output reg  [7:0]  pkt_cnt
);

    localparam S_IDLE = 2'd0, S_SEND = 2'd1, S_DRAIN = 2'd2, S_GAP = 2'd3;

    reg [1:0]  st;
    reg        go_q;
    reg [2:0]  pat;
    reg        sync_on;
    reg [2:0]  sync_left;      // SYNC bytes still to send
    reg [15:0] idx;            // body byte index
    reg [15:0] nbody;          // body length
    reg [15:0] gcnt;
    reg [15:0] crc;
    reg [6:0]  lfsr;
    reg [7:0]  ubuf [0:63];

    assign seq_busy = (st != S_IDLE);

    always @(posedge clk60)
        if (buf_we) ubuf[buf_waddr] <= buf_wdata;

    // ---- Test_Packet ROM (generated by sim/usbpat.py, CRC16 = B6h CEh) ----
    reg [7:0] rom_q;
    always @(*) begin
        case (idx[5:0])
                6'd0: rom_q = 8'hC3;
                6'd1: rom_q = 8'h00;
                6'd2: rom_q = 8'h00;
                6'd3: rom_q = 8'h00;
                6'd4: rom_q = 8'h00;
                6'd5: rom_q = 8'h00;
                6'd6: rom_q = 8'h00;
                6'd7: rom_q = 8'h00;
                6'd8: rom_q = 8'h00;
                6'd9: rom_q = 8'h00;
                6'd10: rom_q = 8'hAA;
                6'd11: rom_q = 8'hAA;
                6'd12: rom_q = 8'hAA;
                6'd13: rom_q = 8'hAA;
                6'd14: rom_q = 8'hAA;
                6'd15: rom_q = 8'hAA;
                6'd16: rom_q = 8'hAA;
                6'd17: rom_q = 8'hAA;
                6'd18: rom_q = 8'hEE;
                6'd19: rom_q = 8'hEE;
                6'd20: rom_q = 8'hEE;
                6'd21: rom_q = 8'hEE;
                6'd22: rom_q = 8'hEE;
                6'd23: rom_q = 8'hEE;
                6'd24: rom_q = 8'hEE;
                6'd25: rom_q = 8'hEE;
                6'd26: rom_q = 8'hFE;
                6'd27: rom_q = 8'hFF;
                6'd28: rom_q = 8'hFF;
                6'd29: rom_q = 8'hFF;
                6'd30: rom_q = 8'hFF;
                6'd31: rom_q = 8'hFF;
                6'd32: rom_q = 8'hFF;
                6'd33: rom_q = 8'hFF;
                6'd34: rom_q = 8'hFF;
                6'd35: rom_q = 8'hFF;
                6'd36: rom_q = 8'hFF;
                6'd37: rom_q = 8'hFF;
                6'd38: rom_q = 8'h7F;
                6'd39: rom_q = 8'hBF;
                6'd40: rom_q = 8'hDF;
                6'd41: rom_q = 8'hEF;
                6'd42: rom_q = 8'hF7;
                6'd43: rom_q = 8'hFB;
                6'd44: rom_q = 8'hFD;
                6'd45: rom_q = 8'hFC;
                6'd46: rom_q = 8'h7E;
                6'd47: rom_q = 8'hBF;
                6'd48: rom_q = 8'hDF;
                6'd49: rom_q = 8'hEF;
                6'd50: rom_q = 8'hF7;
                6'd51: rom_q = 8'hFB;
                6'd52: rom_q = 8'hFD;
                6'd53: rom_q = 8'h7E;
                6'd54: rom_q = 8'hB6;
                6'd55: rom_q = 8'hCE;
                default: rom_q = 8'h00;
        endcase
    end

    // ---- CRC16 (USB: reflected 8005h, init FFFFh, sent inverted, low byte first) ----
    function [15:0] crc16_byte;
        input [15:0] c;
        input [7:0]  b;
        integer i;
        reg [15:0] x;
        begin
            x = c ^ {8'h00, b};
            for (i = 0; i < 8; i = i + 1)
                x = x[0] ? ((x >> 1) ^ 16'hA001) : (x >> 1);
            crc16_byte = x;
        end
    endfunction

    // ---- PRBS7, 8 bits per byte, LSB first ----
    function [14:0] prbs7_byte;            // {next state, byte}
        input [6:0] s;
        integer i;
        reg [6:0] x;
        reg [7:0] o;
        begin
            x = s;
            for (i = 0; i < 8; i = i + 1) begin
                o[i] = x[6];
                x = {x[5:0], x[6] ^ x[5]};
            end
            prbs7_byte = {x, o};
        end
    endfunction

    // ---- body byte of the current index ----
    wire [14:0] prbs_nx = prbs7_byte(lfsr);
    reg  [7:0]  body_q;
    always @(*) begin
        case (pat)
            3'd1:    body_q = ubuf[idx[5:0]];
            3'd2:    body_q = 8'hFF;
            3'd3,
            3'd4:    body_q = 8'h00;
            3'd5:    body_q = (idx == 16'd0)         ? 8'hC3 :
                              (idx == nbody - 16'd2) ? ~crc[7:0] :
                              (idx == nbody - 16'd1) ? ~crc[15:8] : prbs_nx[7:0];
            default: body_q = rom_q;
        endcase
    end

    wire [7:0] sync_q = (sync_left == 3'd1) ? 8'h80 : 8'h00;   // last SYNC byte 80h
    wire       acc    = in_valid & in_ready;

    // next byte presented after an accept (registered output, so in_data is a flop)
    always @(posedge clk60 or negedge rst_n) begin
        if (!rst_n) begin
            st <= S_IDLE; go_q <= 1'b0; pat <= 3'd0; sync_on <= 1'b0; sync_left <= 3'd0;
            idx <= 16'd0; nbody <= 16'd0; gcnt <= 16'd0; crc <= 16'hFFFF; lfsr <= 7'h7F;
            speed <= 2'b00; bypass_en <= 1'b0; eop_dis <= 1'b0; lead_first <= 1'b0;
            in_valid <= 1'b0; in_data <= 8'h00; in_last <= 1'b0; pkt_cnt <= 8'h00;
        end else begin
            go_q <= go;
            case (st)
                S_IDLE: begin
                    in_valid <= 1'b0;
                    if (go & ~go_q) begin
                        pat        <= pattern;
                        speed      <= speed_cfg;
                        bypass_en  <= (pattern >= 3'd2) & (pattern <= 3'd4);
                        eop_dis    <= (pattern >= 3'd2) & (pattern <= 3'd4);
                        lead_first <= (pattern >= 3'd2) & (pattern <= 3'd4);
                        sync_on    <= ~sync_dis_cfg & ~((pattern >= 3'd2) & (pattern <= 3'd4));
                        st         <= S_SEND;
                        idx        <= 16'd0;
                        crc        <= 16'hFFFF;
                        lfsr       <= 7'h7F;
                        // body length: Test_Packet 56, user len (1..64), J/K/chirp len,
                        // PRBS7 PID + len + 2
                        case (pattern)
                            3'd1:    nbody <= (len == 16'd0) ? 16'd1 : ((len > 16'd64) ? 16'd64 : len);
                            3'd2, 3'd3, 3'd4:
                                     nbody <= (len == 16'd0) ? 16'd1 : len;
                            3'd5:    nbody <= len + 16'd3;
                            default: nbody <= 16'd56;
                        endcase
                        if (~sync_dis_cfg & ~((pattern >= 3'd2) & (pattern <= 3'd4)))
                            sync_left <= (speed_cfg == 2'b00) ? 3'd4 : 3'd1;
                        else
                            sync_left <= 3'd0;
                    end
                end

                S_SEND: begin
                    if (!in_valid || acc) begin
                        // present the next byte (or finish)
                        if (in_valid && in_last) begin
                            in_valid <= 1'b0;
                            in_last  <= 1'b0;
                            st       <= S_DRAIN;
                        end else if (sync_left != 3'd0) begin
                            in_valid  <= 1'b1;
                            in_data   <= sync_q;
                            in_last   <= 1'b0;
                            sync_left <= sync_left - 3'd1;
                        end else begin
                            in_valid <= 1'b1;
                            in_data  <= body_q;
                            in_last  <= (idx == nbody - 16'd1);
                            idx      <= idx + 16'd1;
                            // CRC over the PRBS payload (after the PID, before the CRC)
                            if (pat == 3'd5 && idx != 16'd0 && idx < nbody - 16'd2) begin
                                crc  <= crc16_byte(crc, prbs_nx[7:0]);
                                lfsr <= prbs_nx[14:8];
                            end
                        end
                    end
                end

                S_DRAIN: begin                       // wait until the packet has left the path
                    if (!path_busy) begin
                        pkt_cnt <= pkt_cnt + 8'd1;
                        gcnt    <= gap;
                        st      <= S_GAP;
                    end
                end

                default: begin                       // S_GAP
                    if (gcnt != 16'd0)
                        gcnt <= gcnt - 16'd1;
                    else if (rpt && go) begin
                        st        <= S_SEND;
                        idx       <= 16'd0;
                        crc       <= 16'hFFFF;
                        lfsr      <= 7'h7F;
                        sync_left <= sync_on ? ((speed == 2'b00) ? 3'd4 : 3'd1) : 3'd0;
                    end else
                        st <= S_IDLE;
                end
            endcase
        end
    end

endmodule
