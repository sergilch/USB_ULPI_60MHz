#!/usr/bin/env python3
"""run_sims.py - ngspice characterisation of the discrete HS receiver, squelch and
disconnect detector (afe_receiver on the receiver board)

Usage:  python3 AFE/Discrete/Receiver/sim/run_sims.py [case-filter ...] [--force] [--reeval]
        (JOBS=n parallel runs; results in sim/results/<case>/, summary in
        sim/results/summary.json)

Circuit (schematic sheet 2/3, doc section 4): the line passes through the board
(USB-B -> USB-A).  Two BFT92 emitter followers (22 Ohm base stoppers, 220 Ohm
emitter pull-ups) tap D+ / D-.  Their emitters feed
  - the HS receiver SN65LVDS100 (RX_OUT_P/N, LVDS to the FPGA),
  - two TLV3603 window comparators for squelch (|vd| > 0.1 * V_SQ) and two for
    disconnect (|vd| > 0.5 * V_DISC) through resistive offset networks,
  - per detector a BAS70-05 diode-OR envelope (R_att, C_env, R_dec) and a TLV3603
    envelope comparator (threshold V_ETH, 30 mV hysteresis) -> SQ_ACT / DC_ACT.
SQUELCH_A = NAND(SQ_ACT, RX_EN) and DISC_A = AND(DC_ACT, RX_EN) are 74LVC1G gates at
VADJ: not simulated, their delay (datasheet) is added in the evaluation.

Line source: an ideal HS driver (Thevenin 2A behind 45 Ohm per wire, 500 ps 10-90 %
edges), 0.5 m cable, the board, and either
  tap   0.5 m cable to a device with 45 Ohm terminations; board termination off
  term  board termination on (FSUSB42 + 40.2 Ohm), USB-A open

Cases
  eye_<mode>       Test_Packet: line eye at the device / tap, RX_OUT jitter and delay,
                   squelch / disconnect timing and glitches
  ref_tap          same line without the board's tap (loading reference)
  sq_<corner>      bursts of SYNC (KJKJ..) at 80 .. 170 mV, 5 mV steps: squelch trip
  dc_<corner>      bursts of SYNC + 8-bit EOP run at 480 .. 680 mV: disconnect trip
  fs               full-speed J/K/SE0 (3.3 V) through the followers
"""
import json
import os
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor, as_completed

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import usbpat  # noqa: E402

RES = os.path.join(HERE, "results")
LIB = os.path.join(HERE, "models", "rx_models.lib")
UI = 1e9 / 480e6 * 1e-9          # 2.0833 ns
T0 = 20e-9                       # first bit
TR = 0.625e-9                    # source edge 0-100 % (10-90 % = 500 ps)
SOLVER_OPTS = ["reltol=1e-4 method=trap", "reltol=1e-3 method=trap",
               "reltol=1e-3 method=trap gmin=1e-10", "reltol=1e-3 method=gear",
               "reltol=2e-3 method=trap gmin=1e-9 abstol=1e-10 vntol=1e-5"]
T_GATE = 2.5e-9                  # 74LVC1G00 / 1G08 tpd at VADJ 2.5 V (typ, CL 15 pF)

# ---- component values (keep equal to the schematic / doc section 4) ----
VAL = dict(Rbs=22.0, Re=220.0,                       # follower base stopper, emitter pull-up
           Ra_sq=200.0, Rb_sq=2000.0,                # squelch offset network: trip = 0.1 V_SQ
           Ra_dc=499.0, Rb_dc=1000.0,                # disconnect network: trip = 0.499 V_DISC
           Ratt=150.0, Cenv=6.8e-12, Rdec_sq=1500.0, Rdec_dc=680.0,
           Reth_t=18e3, Reth_b=10e3,                 # V_ETH = 3.3 * 10/28 = 1.18 V
           Rterm=40.2, Ron=4.5, Rdev=45.0)
V_SQ, V_DISC = 1.320, 1.210      # DAC codes 1320 / 1210 (1 mV / LSB), centred by the sq_nom / dc_nom sweeps


def pwl(name, n1, n2, vals, t0=T0, tr=TR):
    """PWL source, one value per UI from t0, linear edges of length tr."""
    pts = [(0.0, vals[0])]
    prev = vals[0]
    for i, v in enumerate(vals):
        t = t0 + i * UI
        if v != prev:
            pts += [(t, prev), (t + tr, v)]
            prev = v
    body = " ".join("%.5e %.5f" % p for p in pts)
    lines, cur = [], "%s %s %s PWL(" % (name, n1, n2)
    for tok in body.split(" "):
        if len(cur) > 100:
            lines.append(cur)
            cur = "+"
        cur += " " + tok
    return "\n".join(lines + [cur + ")"])


def tline(name, a, c, z0, td):
    return ["O%s %s 0 %s 0 lt_%s" % (name, a, c, name),
            ".model lt_%s ltra r=0 g=0 l=%g c=%g len=1" % (name, z0 * td, td / z0)]


COLS = ["t", "tp", "tm", "fp", "fm", "ep", "em", "ry", "rz", "sqa", "sqb", "envs", "sqact",
        "envd", "dcact"]


def netlist(c):
    V = VAL
    vdd = c["vdd"]
    L = ["* discrete USB HS receiver - generated by run_sims.py",
         ".include %s" % LIB,
         ".options temp=%g tnom=27 reltol=1e-4 method=trap" % c["temp"],
         "VDD vdd 0 %g" % vdd,
         "VSQ vsqs 0 %g" % c.get("v_sq", V_SQ), "RSQ vsqs vsq 1", "CSQ vsq 0 100n",
         "VDC vdcs 0 %g" % c.get("v_disc", V_DISC), "RDC vdcs vdisc 1", "CDC vdisc 0 100n",
         "RET1 vdd veth %g" % V["Reth_t"], "RET2 veth 0 %g" % V["Reth_b"], "CET veth 0 100n"]
    has_tap = c.get("tap", True)
    for w, vals in (("p", c["dp"]), ("m", c["dm"])):
        # host driver (Thevenin), 0.5 m cable, USB-B, 10 mm trace, ESD, tap, switch, USB-A
        L.append(pwl("VS%s" % w, "s%s" % w, "0", [2 * v for v in vals]))
        L.append("RS%s s%s h%s 45" % (w, w, w))
        L.append("CH%s h%s 0 2p" % (w, w))
        L += tline("CA" + w, "h" + w, "b" + w, 45.0, 2.5e-9)
        L.append("CB%s b%s 0 0.5p" % (w, w))                      # USB-B receptacle
        L += tline("T1" + w, "b" + w, "x" + w, 45.0, 60e-12)
        L.append("CX%s x%s 0 0.85p" % (w, w))                     # USBLC6-2 I/O
        L += tline("T2" + w, "x" + w, "t" + w, 45.0, 30e-12)
        L.append("CT%s t%s 0 0.3p" % (w, w))                      # tap pads
        if has_tap:
            L.append("RBS%s t%s bq%s %g" % (w, w, w, V["Rbs"]))
            L.append("LB%s bq%s bb%s 0.8n" % (w, w, w))
            L.append("RLB%s bq%s bb%s 100" % (w, w, w))
            L.append("Q%s 0 bb%s ex%s BFT92" % (w, w, w))
            L.append("LE%s ex%s e%s 0.8n" % (w, w, w))
            L.append("RLE%s ex%s e%s 100" % (w, w, w))
            L.append("RE%s vdd e%s %g" % (w, w, V["Re"]))
            L.append("CE%s e%s 0 0.5p" % (w, w))
        L += tline("T3" + w, "t" + w, "u" + w, 45.0, 30e-12)
        L.append("CU%s u%s 0 1.9p" % (w, w))                      # FSUSB42 common side
        if c["mode"] == "term":
            L.append("RON%s u%s k%s %g" % (w, w, w, V["Ron"]))
            L.append("CK%s k%s 0 1.8p" % (w, w))
            L.append("RTM%s k%s 0 %g" % (w, w, V["Rterm"]))
        else:
            L.append("CK%s u%s 0 1.8p" % (w, w))                  # selected open port
        L += tline("T4" + w, "u" + w, "a" + w, 45.0, 60e-12)
        L.append("CA%s a%s 0 0.5p" % (w, w))                      # USB-A receptacle
        if c["mode"] == "tap":
            L += tline("CD" + w, "a" + w, "f" + w, 45.0, 2.5e-9)
            L.append("CF%s f%s 0 2p" % (w, w))
            L.append("RF%s f%s 0 %g" % (w, w, V["Rdev"]))
        else:
            L.append("RF%s a%s f%s 1" % (w, w, w))
            L.append("RFX%s f%s 0 1G" % (w, w))
    if has_tap:
        vos = c.get("vos", 0.0)
        L.append("XRX ep em vdd ry rz lvds100")
        L += tline("RXP", "ry", "ryf", 50.0, 0.4e-9) + tline("RXN", "rz", "rzf", 50.0, 0.4e-9)
        L.append("RRX ryf rzf 100")
        # window comparators (A: +vd, B: -vd), offset networks
        for nm, (pos, neg), ra, rb, vref in (
                ("sqa", ("ep", "em"), V["Ra_sq"], V["Rb_sq"], "vsq"),
                ("sqb", ("em", "ep"), V["Ra_sq"], V["Rb_sq"], "vsq"),
                ("dca", ("ep", "em"), V["Ra_dc"], V["Rb_dc"], "vdisc"),
                ("dcb", ("em", "ep"), V["Ra_dc"], V["Rb_dc"], "vdisc")):
            L += ["RA1%s %s ip%s %g" % (nm, pos, nm, ra), "RB1%s ip%s 0 %g" % (nm, nm, rb),
                  "RA2%s %s in%s %g" % (nm, neg, nm, ra), "RB2%s in%s %s %g" % (nm, nm, vref, rb),
                  "CP%s ip%s 0 0.3p" % (nm, nm), "CN%s in%s 0 0.3p" % (nm, nm),
                  "X%s ip%s in%s vdd %s tlv360x vos=%g" % (nm, nm, nm, nm, vos)]
        # diode-OR envelopes and envelope comparators (TLV3603, 30 mV hysteresis)
        for env, (a, b), rdec, out in (("envs", ("sqa", "sqb"), V["Rdec_sq"], "sqact"),
                                       ("envd", ("dca", "dcb"), V["Rdec_dc"], "dcact")):
            for x in (a, b):
                L += ["RAT%s %s at%s %g" % (x, x, x, V["Ratt"]), "D%s at%s %s BAS70" % (x, x, env)]
            L += ["CEV%s %s 0 %g" % (env, env, V["Cenv"]), "RDE%s %s 0 %g" % (env, env, rdec),
                  "X%s %s veth vdd %s tlv360x hys=30m" % (out, env, out),
                  "CL%s %s 0 3p" % (out, out)]                     # gate input + trace
    else:
        L += ["V%s %s 0 0" % (n, n) for n in ("ep", "em", "ryf", "rzf", "sqa", "sqb", "envs",
                                               "sqact", "envd", "dcact")]
    # store only the written vectors (all nodes: > 2 GB per sweep run)
    L.append(".save v(tp) v(tm) v(fp) v(fm) v(ep) v(em) v(ryf) v(rzf) v(sqa) v(sqb) v(envs) "
             "v(sqact) v(envd) v(dcact)")
    L.append(".tran %g %g 0 %g" % (c.get("tstep", 5e-12), c["t_stop"], c.get("tstep", 5e-12)))
    L += [".control", "set wr_singlescale", "set wr_vecnames", "option numdgt=7", "run",
          "wrdata %s v(tp) v(tm) v(fp) v(fm) v(ep) v(em) v(ryf) v(rzf) v(sqa) v(sqb) v(envs) "
          "v(sqact) v(envd) v(dcact)" % c["out"], "quit", ".endc", ".end"]
    return "\n".join(L) + "\n"


KEEP_WAVE = ("eye_tap", "eye_term", "sq_nom", "dc_nom", "fs", "ref_tap")


def run_case(name, c):
    d = os.path.join(RES, name)
    os.makedirs(d, exist_ok=True)
    c = dict(c, out=os.path.join(d, "wave.txt"))
    cir = os.path.join(d, "tb.cir")
    base = netlist(c)
    for opt in SOLVER_OPTS:
        open(cir, "w").write(base.replace("reltol=1e-4 method=trap", opt))
        if os.path.exists(c["out"]):
            os.remove(c["out"])
        r = subprocess.run(["ngspice", "-b", cir], capture_output=True, text=True, timeout=7200)
        open(os.path.join(d, "log.txt"), "w").write(r.stdout + r.stderr)
        if os.path.exists(c["out"]) and "Timestep too small" not in r.stdout + r.stderr:
            break
    else:
        raise RuntimeError("%s: ngspice failed with every solver setting, see %s" % (name, d))
    return load_wave(name)


def load_wave(name):
    w = np.loadtxt(os.path.join(RES, name, "wave.txt"), skiprows=1)
    return {k: w[:, i] for i, k in enumerate(COLS)}


def cross(t, y, lvl, t_from=0.0, rising=None):
    s = y - lvl
    idx = np.where((s[:-1] * s[1:] < 0) & (t[:-1] >= t_from))[0]
    out = []
    for i in idx:
        if rising is not None and (s[i + 1] > s[i]) != rising:
            continue
        out.append(t[i] - s[i] * (t[i + 1] - t[i]) / (s[i + 1] - s[i]))
    return out


# ---------------------------------------------------------------- stimuli
def corner(vdd=3.3, temp=27, **kw):
    return dict(vdd=vdd, temp=temp, **kw)


def eye_case(cfg, mode, amp=0.4):
    line = usbpat.hs_packet_line()
    idle = 12
    bits = [None] * idle + line + [None] * 24          # None = HS idle (SE0)
    dp = [0.0 if b is None else amp * b for b in bits]
    dm = [0.0 if b is None else amp * (1 - b) for b in bits]
    return dict(cfg, mode=mode, dp=dp, dm=dm, bits=bits, first_ui=idle, n_line=len(line),
                t_stop=T0 + len(bits) * UI)


SQ_AMPS = [0.080 + 0.005 * i for i in range(19)]       # 80 .. 170 mV
DC_AMPS = [0.480 + 0.010 * i for i in range(21)]       # 480 .. 680 mV
BURST_IDLE = 40                                         # UI of SE0 between bursts (83 ns)


def burst_case(cfg, amps, eop):
    """bursts of 32 SYNC bits (KJKJ..KK) [+ 8-bit EOP run], one amplitude each"""
    sync = usbpat.nrzi(usbpat.bits_lsb(usbpat.HS_SYNC))
    pat = sync + ([sync[-1] ^ 1] * 8 if eop else [])
    bits, starts = [None] * 8, []
    for a in amps:
        starts.append(len(bits))
        bits += [(a, b) for b in pat] + [None] * BURST_IDLE
    dp = [0.0 if x is None else x[0] * x[1] for x in bits]
    dm = [0.0 if x is None else x[0] * (1 - x[1]) for x in bits]
    return dict(cfg, mode="term", dp=dp, dm=dm, amps=amps, starts=starts, plen=len(pat),
                t_stop=T0 + len(bits) * UI, tstep=10e-12)


def fs_case(cfg):
    """FS J K K J SE0 SE0 J (12 Mb/s, 3.3 V, 4 ns edges) through the followers"""
    seq = [(1, 0), (0, 1), (0, 1), (1, 0), (0, 0), (0, 0), (1, 0), (1, 0)]
    n = 40                                              # UI (2.08 ns) per FS bit
    dp, dm = [], []
    for p, m in seq:
        dp += [1.65 * p] * n
        dm += [1.65 * m] * n
    return dict(cfg, mode="term", dp=dp, dm=dm, t_stop=T0 + len(dp) * UI, tstep=20e-12,
                fs_n=n, fs_seq=seq)


# ---------------------------------------------------------------- evaluation
def line_eye(t, d, bits, first_ui, n_line):
    """eye at the line: delay of the first edge, height at the bit centres, jitter"""
    t0 = T0 + first_ui * UI
    tend = t0 + (n_line - 8) * UI
    # the packet starts from SE0 (0 V): time the first full-swing edge, SYNC bit 1 (K -> J)
    z1 = cross(t, d, 0.0, t0 + UI / 2, rising=True)[0]
    delay = z1 - (t0 + UI + TR / 2)
    zc = [z for z in cross(t, d, 0.0, z1 - 1e-12) if z < tend + UI]
    ph = np.array([(z - t0 - delay - TR / 2) % UI for z in zc])
    ph = np.where(ph > UI / 2, ph - UI, ph)
    hi, lo = [], []
    for i in range(n_line - 8):
        v = float(np.interp(t0 + delay + TR / 2 + (i + 0.5) * UI, t, d))
        (hi if bits[first_ui + i] else lo).append(v)
    return dict(delay_ns=1e9 * delay, jitter_pp_ps=1e12 * float(ph.max() - ph.min()),
                eye_height_mV=1e3 * (min(hi) - max(lo)), vJ_mV=1e3 * float(np.median(hi)),
                vK_mV=1e3 * float(np.median(lo)))


def det_times(t, y, vdd):
    """rising / falling crossing times of a 0..vdd logic node at vdd/2"""
    return cross(t, y, vdd / 2, rising=True), cross(t, y, vdd / 2, rising=False)


def eval_eye(w, c):
    t = w["t"]
    r = dict(device=line_eye(t, w["fp"] - w["fm"], c["bits"], c["first_ui"], c["n_line"]),
             tap=line_eye(t, w["tp"] - w["tm"], c["bits"], c["first_ui"], c["n_line"]))
    if not c.get("tap", True):
        return r
    # RX_OUT: delay from the tap's crossing, jitter relative to the bit grid
    rx = line_eye(t, w["ry"] - w["rz"], c["bits"], c["first_ui"], c["n_line"])
    r["rx_out"] = dict(delay_ns=rx["delay_ns"] - r["tap"]["delay_ns"],
                       jitter_pp_ps=rx["jitter_pp_ps"], vod_mV=rx["vJ_mV"])
    # squelch / disconnect: activity = first edge at the tap .. end of the EOP
    t_act = T0 + c["first_ui"] * UI + r["tap"]["delay_ns"] * 1e-9 + TR / 2
    t_end = T0 + (c["first_ui"] + c["n_line"]) * UI + r["tap"]["delay_ns"] * 1e-9 + TR / 2
    up, dn = det_times(t, w["sqact"], c["vdd"])
    r["squelch"] = dict(t_on_ns=1e9 * (up[0] - t_act + T_GATE) if up else None,
                        t_off_ns=1e9 * (dn[-1] - t_end + T_GATE) if dn else None,
                        glitches=max(len(up) - 1, 0) + max(len(dn) - 1, 0))
    dup, ddn = det_times(t, w["dcact"], c["vdd"])
    r["disc"] = dict(events=len(dup))
    return r


def eval_burst(w, c, node):
    """per burst: detector asserted? + measured |vd| at the tap (bit centres)"""
    t = w["t"]
    d = w["tp"] - w["tm"]
    out = []
    for a, s in zip(c["amps"], c["starts"]):
        ta, tb = T0 + s * UI, T0 + (s + c["plen"] + BURST_IDLE) * UI
        m = (t >= ta) & (t < tb)
        on = bool(np.max(w[node][m]) > c["vdd"] / 2)
        vs = [abs(float(np.interp(T0 + (s + i + 0.5) * UI + 0.5e-9, t, d)))
              for i in range(4, c["plen"])]
        out.append(dict(amp_mV=1e3 * a, vd_mV=1e3 * float(np.median(vs)), on=on))
    off = [b["vd_mV"] for b in out if not b["on"]]
    on = [b["vd_mV"] for b in out if b["on"]]
    # trip point: between the largest burst that did not trigger and the smallest that did
    return dict(bursts=out, max_off_mV=max(off) if off else None, min_on_mV=min(on) if on else None,
                trip_mV=(max(off) + min(on)) / 2 if off and on else None,
                monotonic=all(not b["on"] for b in out[:len(off)]) and all(b["on"] for b in out[len(off):]))


def eval_fs(w, c):
    t = w["t"]
    res = []
    for i, (p, m) in enumerate(c["fs_seq"]):
        tm_ = T0 + (i + 0.8) * c["fs_n"] * UI
        res.append(dict(dp=p, dm=m, rx=round(float(np.interp(tm_, t, w["ry"] - w["rz"])), 3),
                        ep=round(float(np.interp(tm_, t, w["ep"])), 3),
                        em=round(float(np.interp(tm_, t, w["em"])), 3)))
    ok = all((r["rx"] > 0) == (r["dp"] > r["dm"]) for r in res if r["dp"] != r["dm"])
    return dict(states=res, polarity_ok=ok)


def task_list():
    T = []
    nom = corner()
    T.append(("eye_tap", eye_case(nom, "tap"), "eye"))
    T.append(("eye_term", eye_case(nom, "term"), "eye"))
    T.append(("ref_tap", dict(eye_case(nom, "tap"), tap=False), "eye"))
    T.append(("fs", fs_case(nom), "fs"))
    for vdd in (3.135, 3.3, 3.465):
        for temp in (-40, 27, 85):
            cfg = corner(vdd, temp)
            tag = "nom" if (vdd, temp) == (3.3, 27) else "%g_%g" % (vdd, temp)
            T.append(("sq_" + tag, burst_case(cfg, SQ_AMPS, False), "sq"))
            T.append(("dc_" + tag, burst_case(cfg, DC_AMPS, True), "dc"))
            if tag != "nom":
                T.append(("corner_eye_" + tag, eye_case(cfg, "tap"), "eye"))
    for vos in (-5e-3, 5e-3):                           # TLV3603 offset at its spec limit
        T.append(("sq_vos%+g" % (vos * 1e3), burst_case(corner(vos=vos), SQ_AMPS, False), "sq"))
        T.append(("dc_vos%+g" % (vos * 1e3), burst_case(corner(vos=vos), DC_AMPS, True), "dc"))
    return T


def evaluate(name, c, kind, w):
    if kind == "eye":
        r = eval_eye(w, c)
    elif kind == "sq":
        r = eval_burst(w, c, "sqact")
    elif kind == "dc":
        r = eval_burst(w, c, "dcact")
    else:
        r = eval_fs(w, c)
    r.update(vdd=c["vdd"], temp=c["temp"], vos_mV=1e3 * c.get("vos", 0.0))
    return r


def main():
    args = sys.argv[1:]
    reev = "--reeval" in args
    flt = [a for a in args if not a.startswith("--")]
    want = lambda n: not flt or any(f in n for f in flt)  # noqa: E731
    os.makedirs(RES, exist_ok=True)
    sp = os.path.join(RES, "summary.json")
    summary = json.load(open(sp)) if os.path.exists(sp) else {}
    jobs = int(os.environ.get("JOBS", 2))
    tasks = [t for t in task_list() if want(t[0])]

    def work(t):
        name, c, kind = t
        if reev:
            if not os.path.exists(os.path.join(RES, name, "wave.txt")):
                return name, None
            w = load_wave(name)
        else:
            if name in summary and "error" not in summary[name] and "--force" not in args:
                return name, summary[name]
            try:
                w = run_case(name, c)
            except RuntimeError as e:
                print("%-24s FAILED %s" % (name, e), flush=True)
                return name, dict(error=str(e))
        try:
            r = evaluate(name, c, kind, w)
        except Exception as e:
            r = dict(error=repr(e))
        print("%-24s %s" % (name, json.dumps({k: v for k, v in r.items() if k != "bursts"})[:300]),
              flush=True)
        wf = os.path.join(RES, name, "wave.txt")
        if not reev and not name.startswith(KEEP_WAVE) and os.path.exists(wf):
            os.remove(wf)
        return name, r

    with ThreadPoolExecutor(1 if reev else jobs) as ex:
        for fut in as_completed([ex.submit(work, t) for t in tasks]):
            name, r = fut.result()
            if r is not None:
                summary[name] = r
            json.dump(summary, open(sp, "w"), indent=1)


if __name__ == "__main__":
    main()
