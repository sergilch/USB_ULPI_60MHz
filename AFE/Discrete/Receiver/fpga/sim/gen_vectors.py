#!/usr/bin/env python3
"""gen_vectors.py - HS line vectors of the FPGA testbench (packets.vh) and the
packets the decoder must find (expected.json).  Line convention J = 1."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "sim"))
import usbpat as u  # noqa: E402

PKTS = [
    [u.PID_DATA0] + u.TEST_PACKET + u.crc16(u.TEST_PACKET),     # Test_Packet
    u.token(0x69, 5, 1),                                          # IN addr 5 ep 1
    [0xD2],                                                       # ACK
    [0x4B, 0x01, 0x02, 0x03, 0x04] + u.crc16([1, 2, 3, 4]),       # DATA1
]


def main():
    L = ["// packets.vh - generated by gen_vectors.py: HS line bits (J = 1), index 0 first",
         "localparam integer NPKT = %d;" % len(PKTS)]
    for k, p in enumerate(PKTS):
        line = u.hs_line(p)
        L.append("localparam integer PKT%d_N = %d;" % (k, len(line)))
        L.append("localparam [0:%d] PKT%d = %d'b%s;" % (len(line) - 1, k, len(line),
                                                       "".join(str(b) for b in line)))
    open(os.path.join(HERE, "packets.vh"), "w").write("\n".join(L) + "\n")
    json.dump([["%02X" % b for b in p] for p in PKTS], open(os.path.join(HERE, "expected.json"), "w"))


if __name__ == "__main__":
    main()
