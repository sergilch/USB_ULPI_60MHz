#!/usr/bin/env python3
"""xfab2ngspice.py - convert the xh018 3.3 V MOS cards (Spectre) for ngspice

Usage:
    python3 "AFE/Crystal Oscillator Driver/sim/xfab2ngspice.py" [out_dir] [--sigma=3]

Reads the confidential X-FAB library under X-FAB/spice (never copied into the
repository) and writes, by default to build/xosc/models/ (git-ignored):

    xh018_<corner>.lib   for corner in tm ws wp wo wz

Each file holds the corner parameters of mos/<corner>_mos.scs and
dio/<corner>_dio.scs as .param lines (wo / wz use the typical diode set,
there is no wo / wz diode file) and the subcircuits

    ne3i  (d g s b) w= l=     isolated 3.3 V NMOS   (mos/ne3i.scs)
    pe3i  (d g s b) w= l=     isolated 3.3 V PMOS   (mos/pe3i.scs)

with the binned BSIM3v3 cards as ngspice level=8 models <name>mod.<bin>
inside the subcircuit, so that the l-dependent expressions (nfactor) see the
instance length.  The Spectre parameters ngspice's BSIM3 does not know (lmlt,
wmlt, tlev, tlevc, minr, diomod) are left out; they are 1 / 1 / 1 / 1 / 1e-3
/ 0 in the source, i.e. defaults.  The mismatch instance terms (delvt0,
mulu0 with avt = au0 = 0 in all corners) are dropped.  Only the
xf_subext = 0 branch is converted.

The worst-case corner files scale with the sigma parameters xsf__* of
param.scs (sections 2s..6s); --sigma sets them (default 3, the 3s section).
Corner names follow X-FAB: tm typical, ws worst speed (slow N / slow P),
wp worst power (fast / fast), wo fast N / slow P, wz slow N / fast P.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
XF = os.path.join(ROOT, "X-FAB", "spice")
CORNERS = ["tm", "ws", "wp", "wo", "wz"]
DROP = {"lmlt", "wmlt", "tlev", "tlevc", "minr", "diomod"}


def read_params(path):
    """'+name=value' lines of a Spectre 'parameters' file -> list of (k, v)."""
    out = []
    for line in open(path):
        m = re.match(r"^\+\s*([A-Za-z_][\w]*)\s*=\s*(\S+)", line)
        if m:
            out.append((m.group(1), m.group(2)))
    return out


def expr(v):
    """Spectre value -> ngspice value ('{...}' around expressions)."""
    v = v.strip()
    if re.fullmatch(r"[-+]?(\d+\.?\d*|\.\d+)([eE][-+]?\d+)?", v):
        return v
    return "{" + v + "}"


def convert_model(path, name):
    txt = open(path).read()
    m = re.search(r"model\s+(\w+)\s+bsim3v3\s*\{(.*?)\n\s*\}", txt, re.S)
    if not m:
        raise SystemExit(f"no bsim3v3 model block in {path}")
    mname, body = m.group(1), m.group(2)
    bins = re.split(r"^\s*(\d+):\s*", body, flags=re.M)[1:]
    cards = []
    for i in range(0, len(bins), 2):
        num, chunk = bins[i], bins[i + 1]
        params, seen = [], set()
        for k, v in re.findall(r"([A-Za-z_]\w*)\s*=\s*(\([^=]*?\)(?=\s+[A-Za-z_]\w*\s*=|\s*$)|\S+)",
                               chunk, re.M):
            k = k.lower()
            if k in DROP or k in seen:
                continue
            seen.add(k)
            if k == "type":
                typ = "nmos" if v.strip() == "n" else "pmos"
                continue
            if k == "version":
                params.append("+ version=3.2.4")
                continue
            params.append(f"+ {k}={expr(v)}")
        cards.append(f".model {mname}.{num} {typ} level=8\n" + "\n".join(params))
    inst = (f"m1 d g s b {mname} w={{w}} l={{l}} ad={{0.48e-6*w}} as={{0.48e-6*w}}\n"
            f"+ pd={{2*w+0.96e-6}} ps={{2*w+0.96e-6}} nrd={{0.27e-6/w}} nrs={{0.27e-6/w}}")
    return (f".subckt {name} d g s b w=1e-6 l=1e-6\n{inst}\n" + "\n".join(cards)
            + f"\n.ends {name}\n")


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--sigma=")]
    sig = ([a.split("=")[1] for a in sys.argv[1:] if a.startswith("--sigma=")] or ["3"])[0]
    out = args[0] if args else os.path.join(ROOT, "build", "xosc", "models")
    if not os.path.isdir(XF):
        raise SystemExit(f"X-FAB library not found: {XF}")
    os.makedirs(out, exist_ok=True)
    subckts = convert_model(os.path.join(XF, "mos", "ne3i.scs"), "ne3i") + "\n" + \
        convert_model(os.path.join(XF, "mos", "pe3i.scs"), "pe3i")
    for c in CORNERS:
        dio = c if c in ("tm", "ws", "wp") else "tm"
        pars = read_params(os.path.join(XF, "mos", f"{c}_mos.scs")) + \
            read_params(os.path.join(XF, "dio", f"{dio}_dio.scs"))
        lines = [f"* xh018 {c} (generated by xfab2ngspice.py from X-FAB/spice - CONFIDENTIAL, do not commit)"]
        lines += [f".param xsf__{d}={sig}" for d in ("mos", "bip", "dio", "res", "cap", "photo")]
        lines += [f".param {k}={expr(v)}" for k, v in pars]
        open(os.path.join(out, f"xh018_{c}.lib"), "w").write("\n".join(lines) + "\n\n" + subckts)
        print(f"wrote {out}/xh018_{c}.lib ({len(pars)} parameters)")


if __name__ == "__main__":
    main()
